/// The bytes to upload, what to call them in the log and on the bar, and
/// whether they are a Windows CE boot file (which changes how it is entered).
///
/// POINT AT THE IMAGE, NOT AT A FILE YOU EXTRACTED FROM IT. A disc already says
/// which file it boots (IP.BIN names it) and where that file is, so extracting
/// `1ST_READ.BIN` by hand and then passing two paths that have to agree is work
/// nobody needs to do -- and one of the two being stale is a whole debugging
/// session.
/// `opened` is the image already open for the syscall loop, when the thing
/// being run IS that image -- which is the usual case, and re-opening it here
/// would re-read the zip directory and re-probe every track for nothing.
fn resolve_payload(
    args: &Args,
    file: &str,
    opened: Option<&dyn disc_formats::types::DiscFormat>,
) -> Result<(Vec<u8>, String, bool), String> {
    let boot = match opened {
        Some(disc) => Some(
            disc_formats::boot::extract(disc, args.descramble.into(), args.wince_mode())
                .map_err(|e| format!("{file}: {e}"))?,
        ),
        None if dispatch::is_disc_image(file) => {
            Some(dispatch::boot_binary(file, args.descramble.into(), args.wince_mode())?)
        }
        None => None,
    };
    if let Some(boot) = boot {
        info!(
            "{file}: booting {} ({} bytes, LBA {})",
            boot.name,
            indicatif::HumanBytes(boot.bytes.len() as u64),
            boot.lba
        );
        return Ok((boot.bytes, boot.name, boot.wince));
    }
    dispatch::payload_from_file(std::path::Path::new(file))
        .map(|(bytes, label)| (bytes, label, false))
        .map_err(|e| format!("{file}: {e}"))
}

/// Which image serves the title's disc reads.
///
/// When the thing being run IS a disc image, it is also the disc -- that is the
/// whole point of pointing at it. An explicit `-d` still wins, and `-m` (host
/// filesystem instead of a disc) turns it off.
fn effective_disc(file: &str, disc: &Option<String>, mount: &Option<String>) -> Option<String> {
    if disc.is_some() {
        return disc.clone();
    }
    if mount.is_some() {
        return None;
    }
    dispatch::is_disc_image(file).then(|| file.to_string())
}

/// `ADDR=N[:PEEK]` for `--probe`. N is 1..=127.
///
/// Without PEEK, N only names the probe and the reported buffer is the stub's
/// own literal pool -- "this address was executed" and nothing more.
///
/// With PEEK, the stub reports N bytes read FROM PEEK instead, so reaching the
/// site also exfiltrates memory: `--probe 0x8c0100f2=4:0x8c0000bc` says "when
/// the title gets here, show me the four bytes of the GD syscall vector". That
/// is the only way to look at the title's RAM at a chosen instant, because
/// dcload does not run again until a GD syscall and a probe stops the title
/// before one can happen.
fn parse_probe(s: &str) -> Result<(u32, u8, Option<u32>), String> {
    let (addr, rest) = s
        .split_once('=')
        .ok_or_else(|| format!("expected ADDR=N[:PEEK], got '{s}'"))?;
    let (n, peek) = match rest.split_once(':') {
        Some((n, p)) => (n, Some(p)),
        None => (rest, None),
    };
    let num = |t: &str| -> Result<u32, String> {
        let t = t.trim();
        let r = if let Some(h) = t.strip_prefix("0x").or_else(|| t.strip_prefix("0X")) {
            u32::from_str_radix(h, 16)
        } else {
            t.parse::<u32>()
        };
        r.map_err(|e| format!("'{t}': {e}"))
    };
    let addr = num(addr)?;
    let n = num(n)?;
    if n == 0 || n > 127 {
        return Err(format!("probe length/id must be 1..=127, got {n}"));
    }
    let peek = peek.map(num).transpose()?;
    Ok((addr, n as u8, peek))
}

/// `ADDR=VALUE`, both decimal or 0x-hex, for `--patch`.
fn parse_patch(s: &str) -> Result<(u32, u32), String> {
    let (addr, value) = s
        .split_once('=')
        .ok_or_else(|| format!("expected ADDR=VALUE, got `{s}`"))?;
    Ok((
        maybe_hex::<u32>(addr.trim())?,
        maybe_hex::<u32>(value.trim())?,
    ))
}

/// Work out which base the loader should be at for this disc, and say why.
///
/// Returns `None` when there is no reason to move: no disc, no database, no
/// match. The caller keeps the running loader in that case, which is the stock
/// 0x8c004000 and is what every title got before any of this existed.
/// Where to put the loader when the preset's own address is one the title
/// addresses. `None` means there is nowhere better.
///
/// One function, called by `uexec` and by `identify`, because the whole value
/// of the offline report is that it says what a run would actually do.
fn pick_clear_base(
    loaders: &loaders::LoaderSet,
    boot: &[u8],
    address: u32,
    wanted: u32,
    seen: Option<&memmap::MemoryMap>,
    sp_min: Option<u32>,
) -> Option<u32> {
    // WHAT THE TITLE HAS BEEN SEEN USING BEATS WHAT IT MENTIONS.
    //
    // The constant scan is a guess about an allocator and misses every failure
    // measured so far; `game-memory.tsv` is where reads actually landed, in
    // earlier sessions of this same game. Tried with a margin first, because
    // 0x8cfd0000 overlapped nothing and still froze 41 KB from the textures,
    // then without, then not at all -- a rich map must narrow the choice, never
    // empty it.
    for margin in [0x4_0000u32, 0] {
        let strict = |b: u32| base_is_clear(loaders, boot, address, b, seen, sp_min, margin);
        if let Some(found) = choose(loaders, wanted, &strict) {
            if margin == 0 {
                warn!(
                    "0x{found:08x} is clear of where this title's reads have landed, but only \
                     just -- no base was clear of them with room to spare"
                );
            }
            return Some(found);
        }
    }
    if let Some(m) = seen.filter(|m| !m.is_empty()) {
        warn!(
            "every base this host can offer is inside RAM this title has been seen using \
             ({} of 256 blocks of 64 KB); falling back to constants alone, and the result \
             is a guess",
            m.blocks_marked()
        );
    }
    // The constants alone -- but never without the stack test, which is not a
    // heuristic about where a title might allocate. It is a measurement of
    // where its stack has already been, and a base that fails it is one this
    // loader is known not to fit under.
    let is_clear = |b: u32| {
        dispatch::literals_in_loader_footprint(boot, address, b).is_empty()
            && low_base_has_stack_headroom(loaders, b, sp_min)
            && low_loader_painted_by_title(loaders, boot, address, b).is_none()
            && region_reaching_loader(boot, address, b).is_none()
    };
    choose(loaders, wanted, &is_clear)
}

/// The three tests that decide whether a base is safe for a title: what the
/// title NAMES (constants in its binary), where its reads have LANDED (the
/// learned map), and how deep its STACK has been seen going (the learned
/// low-water mark). One definition, because it is asked in three places -- of
/// the base a preset wants, of each alternative, and of the base the loader is
/// already at -- and an answer that differed between them would be worse than
/// no answer.
#[allow(clippy::too_many_arguments)]
fn base_is_clear(
    loaders: &loaders::LoaderSet,
    boot: &[u8],
    address: u32,
    base: u32,
    seen: Option<&memmap::MemoryMap>,
    sp_min: Option<u32>,
    margin: u32,
) -> bool {
    dispatch::literals_in_loader_footprint(boot, address, base).is_empty()
        && !map_hits_loader(base, seen, margin)
        && low_base_has_stack_headroom(loaders, base, sp_min)
        && low_loader_painted_by_title(loaders, boot, address, base).is_none()
        && region_reaching_loader(boot, address, base).is_none()
}

/// How far under a high base a region the title names may start and still be
/// taken to reach it. One block: see `region_reaching_loader`.
const REGION_REACH: u32 = memmap::BLOCK;

/// A region the title names that starts inside a HIGH loader's span, or less
/// than `REGION_REACH` under it: `Some(start)`.
///
/// THE CONSTANT SCAN LOOKS AT THE SPAN, AND A REGION GROWS UPWARD. A title that
/// names 0x8cfc0000 has something that starts there and extends to an address
/// it computes; the scan only asked whether 0x8cfc0000 was inside the loader.
/// Shenmue II is the measured case: 0x8cfc0000 is in its region table, the
/// host put the loader at 0x8cfd0000, and at the end of a cinematic the title
/// wrote 0x8cfd0000..0x8cfd07c0 -- the loader's first 2 KB -- and the console
/// reset (2026-09-30). One block of reach is what that measured, and a region
/// further down is left to the learned map and the memory marks.
///
/// Region starts are 64 KB-aligned words anywhere in the image
/// (`dispatch::region_starts`), not only loaded literals: Shenmue II's are in a
/// data table. A low base shares the BIOS work area with the title by design,
/// and is left to the tests that know about it.
fn region_reaching_loader(boot: &[u8], address: u32, base: u32) -> Option<u32> {
    if !loaders::is_high(base) {
        return None;
    }
    let (lo, hi) = (base.saturating_sub(REGION_REACH), base + loaders::LOADER_SPAN);
    dispatch::region_starts(boot, address)
        .into_iter()
        .find(|&c| lo <= c && c < hi)
}

/// Where the loader goes when DreamShell's preset is right about the RAM but
/// our loader is too big for it.
///
/// A PRESET IS A WINDOW, NOT ONLY AN ADDRESS. DreamShell's `memory` is where
/// isoldr ran for this title, and isoldr is 13 KB: what the preset tells us is
/// that the title leaves `preset..` alone for at least that far. The title's
/// own constants say where the window ends -- the lowest address it names
/// above the preset. When our 64 KB span does not fit (the case where the
/// constant scan refuses the preset itself), the least surprising place is
/// against that ceiling: the most of our span inside the window, the least
/// below it.
///
/// Shenmue II: preset 0x8cfe8000, ceiling 0x8cff0000 (its Maple DMA list, as
/// for Sonic Adventure 2), so 0x8cfe0000 -- measured to run where the old
/// search's 0x8cfd0000 reset the console (2026-09-30).
///
/// Tested with no margin against the map, like a preset: a margin is a guess
/// about an allocator heading somewhere, and this candidate is DreamShell's
/// evidence. Everything else `base_is_clear` asks still applies, the region
/// rule included -- it is what refuses 0x8cfd0000 for Shenmue II.
fn preset_window_base(
    loaders: &loaders::LoaderSet,
    boot: &[u8],
    address: u32,
    preset: u32,
    seen: Option<&memmap::MemoryMap>,
    sp_min: Option<u32>,
) -> Option<(u32, u32)> {
    if !loaders::is_high(preset) {
        return None;
    }
    let ceiling = preset_window_ceiling(boot, address, preset)?;
    let base = ceiling.checked_sub(loaders::LOADER_SPAN)? & !(loaders::LAYOUT_PAGE - 1);
    if base == preset || !loaders::is_high(base) || !loaders.can_provide(base) {
        return None;
    }
    base_is_clear(loaders, boot, address, base, seen, sp_min, 0).then_some((base, ceiling))
}

/// The lowest RAM address above `preset` the title names: a loaded literal or
/// a region start.
fn preset_window_ceiling(boot: &[u8], address: u32, preset: u32) -> Option<u32> {
    let loaded = dispatch::loaded_literals_in(boot, address, &[(preset + 1, 0x8d00_0000)])
        .into_iter()
        .map(|(at, _)| at);
    let regions = dispatch::region_starts(boot, address)
        .into_iter()
        .filter(|&c| c > preset);
    loaded.chain(regions).min()
}

/// Does a loader at `base` fit under this title's stack?
///
/// THE THIRD TEST, AND THE ONLY ONE THAT SEES A STACK. The other two look for
/// an address collision -- RAM the title names, RAM its reads have landed in --
/// and a stack is neither: it descends from 0x8c00f400 into whatever the loader
/// left below it, is named by no constant, and no read is ever served into it.
/// Sonic Adventure at the stock base is the measured case, and it passes both
/// of the other tests (AGENTS.md 4.6, and `loaders::LOW_BASE_MIN_MARGIN` for
/// the two numbers that fix the threshold).
///
/// Three ways to answer "yes" without measuring anything, and each is
/// deliberate:
///
/// - a HIGH base is nowhere near the BIOS work area, so the title has the whole
///   0x8c004000..0x8c00f400 hole to itself;
/// - no `sp_min` recorded means no session has ever read one back. Assuming a
///   depth would reject the stock base for every title on the strength of one
///   game's measurement -- 593 presets ask for that base;
/// - no readable loader image means `_end` is unknown, and a test that cannot
///   be computed must not decide anything.
fn low_base_has_stack_headroom(
    loaders: &loaders::LoaderSet,
    base: u32,
    sp_min: Option<u32>,
) -> bool {
    stack_headroom_ok(base, loaders.image_end_for(base), sp_min)
}

/// The arithmetic on its own, so the two measurements it stands on can be a
/// test rather than a comment.
fn stack_headroom_ok(base: u32, image_end: Option<u32>, sp_min: Option<u32>) -> bool {
    if loaders::is_high(base) {
        return true;
    }
    let (Some(sp), Some(end)) = (sp_min, image_end) else {
        return true;
    };
    sp.saturating_sub(end) >= loaders::LOW_BASE_MIN_MARGIN
}

/// Does the title's own code fill RAM a LOW loader's image sits in?
/// `(lo, hi, site, image_end)` of the first fill that does.
///
/// THE STACK TEST'S BLIND SPOT, AND A WORSE ONE THAN DEPTH. `sp_min` is where
/// the title's stack pointer was when it called the GD driver; a Katana title
/// paints its whole BIOS stack, 0x8c00c000..0x8c00f400, before it calls
/// anything (`dispatch::constant_range_fills`). Snow Surfers entered GD
/// syscalls no lower than 0x8c00e460 -- 6424 bytes over a loader at 0x8c004000,
/// a pass -- and had already written "SEGA" over that loader's `.data` and
/// `.bss`, so the run ended in the BIOS menu (2026-09-17).
///
/// Only the image counts, `base.._end`: everything a low loader keeps above
/// `_end` is its own stack, which the title owns from EXEC on anyway. A high
/// base is answered by `literals_in_loader_footprint`, which does not skip its
/// footprint; this scan is only asked where that one looks away, which also
/// keeps it off the relocation walk's dozens of high candidates.
fn low_loader_painted_by_title(
    loaders: &loaders::LoaderSet,
    boot: &[u8],
    address: u32,
    base: u32,
) -> Option<(u32, u32, u32, u32)> {
    if loaders::is_high(base) {
        return None;
    }
    let end = loaders.image_end_for(base)?;
    fill_over_image(base, end, &dispatch::constant_range_fills(boot, address))
        .map(|(lo, hi, site)| (lo, hi, site, end))
}

/// The overlap on its own, so the Snow Surfers numbers can be a test.
fn fill_over_image(base: u32, end: u32, fills: &[(u32, u32, u32)]) -> Option<(u32, u32, u32)> {
    fills.iter().copied().find(|&(lo, hi, _)| lo < end && base < hi)
}

/// `low_loader_painted_by_title`'s finding as the clause every caller logs.
fn painted_reason(base: u32, (lo, hi, site, end): (u32, u32, u32, u32)) -> String {
    format!(
        "its startup code fills 0x{lo:08x}..0x{hi:08x} (the loop at 0x{site:08x}), while a \
         loader at 0x{base:08x} ends at 0x{end:08x}: the loader's data would be overwritten \
         before the title's first disc read"
    )
}

/// Is the low family contested for this title BY THE DATABASE ITSELF?
///
/// Returns the addresses its presets disagree over, when they disagree and at
/// least one of the votes is below what this host can build.
///
/// WHY THAT COMBINATION IS THE SIGNAL. A title match is ambiguous when several
/// dumps carry the same name and DreamShell gave them different addresses; the
/// tie-break in `presets.rs` then keeps the loader still, which for isoldr's
/// 13 KB is the safe answer. But a vote below 0x8c004000 is not one more
/// opinion: DreamShell reaches `_MIN` only after its default and its high
/// option have BOTH been rejected for a title, so it is that title saying low
/// RAM was too tight -- for a loader a quarter of this one's size. Keeping a
/// 56 KB image at the stock base on the strength of the other vote is choosing
/// the one address the disagreement argues against.
///
/// Measured: 8 titles of the database's 1026 reach this, Sonic Adventure among
/// them -- whose two votes are 0x8c004000 and 0x8c000100, and which corrupts the
/// loader at the first of them.
fn low_family_contested(
    db: &presets::PresetDb,
    identity: &presets::DiscIdentity,
    preset: &presets::Preset,
) -> Option<Vec<u32>> {
    if loaders::is_high(preset.memory) {
        return None;
    }
    let votes = db.title_addresses(&identity.title);
    votes
        .iter()
        .any(|&m| loaders::known_unsupported(m).is_some())
        .then_some(votes)
}

/// Where to put the loader when the LOW FAMILY as a whole is the problem.
///
/// Not `base_for_low_preset`, and the difference is what the preset said. That
/// one answers for a preset this host cannot build, where DreamShell has
/// positively rejected 0x8ce00000 and 0x8cfe8000 for the title and both are
/// therefore struck out. Here the database's own answer for this dump is a
/// SUPPORTED low base -- it is our image's size, or this title's measured
/// stack, that rules it out -- so nothing has been said against the high
/// options at all.
///
/// So for a title in the database the seed is `ISOLDR_HIGH_ADDR`: DreamShell's
/// own second choice, the address it moves isoldr to when low RAM is not
/// workable, and the one 119 presets use. It is checked like any other
/// candidate -- Sonic Adventure 2's preset is that very address and its Maple
/// DMA list rules it out.
///
/// A title the database does not know has no such opinion behind it, and is
/// seeded from `SCRATCH_BASE` instead: one chainload from the disc's stock
/// base, and where Snow Surfers ran every CD-DA session on the console. From
/// `ISOLDR_HIGH_ADDR` its search landed on 0x8cfd0000, which nobody has run.
fn base_off_the_low_family(
    loaders: &loaders::LoaderSet,
    boot: &[u8],
    address: u32,
    seen: Option<&memmap::MemoryMap>,
    sp_min: Option<u32>,
    seed: u32,
) -> Option<u32> {
    let high = seed;
    // SAY WHY THE SEED WAS NOT TAKEN. It is the one address in this branch that
    // anybody has an opinion about -- DreamShell's, and 119 presets' -- so
    // "something else was used instead" without a reason is the line a reader
    // would have to reconstruct by hand.
    if !loaders.can_provide(high) {
        debug!("0x{high:08x} is not an address this loader set can produce");
    } else if !base_is_clear(loaders, boot, address, high, seen, sp_min, 0x4_0000) {
        let hits = dispatch::literals_in_loader_footprint(boot, address, high);
        debug!(
            "0x{high:08x} is ruled out for this title: {} constant(s) point into it{}",
            hits.len(),
            if map_hits_loader(high, seen, 0x4_0000) {
                ", and its reads have landed within 256 KB of it"
            } else {
                ""
            }
        );
    } else {
        return Some(high);
    }
    pick_clear_base(loaders, boot, address, high, seen, sp_min)
}

/// Has this title been seen reading into RAM a loader at `base` would be using?
///
/// Over `exclusive_footprint`, the SAME ranges the constant scan reads. Asking
/// the map about `base..base+LOADER_SPAN` flat is right for a high loader and
/// wrong for a low one, whose span is the BIOS work area: every title uses low
/// RAM, so that test rejects the stock base for all of them. Sonic Adventure's
/// row marks 0x8c030000, and 0x8c004000 is the address 593 presets ask for and
/// the one that title is measured to run at.
fn map_hits_loader(base: u32, seen: Option<&memmap::MemoryMap>, margin: u32) -> bool {
    seen.is_some_and(|m| {
        loaders::exclusive_footprint(base)
            .into_iter()
            .any(|(lo, hi)| m.hits(lo, hi - lo, margin))
    })
}

/// Where to put the loader when the preset's address is one this host cannot
/// build at all -- 276 of the database's 1026 rows, every one of them below the
/// BIOS syscall area.
///
/// THE PRESET STILL ANSWERS, IN THE NEGATIVE. `ruled_out_by_low_preset` is that
/// reading: DreamShell reached for 0x8ce00000 and then 0x8cfe8000 before it gave
/// up and went low, so those two are the last places this title's loader should
/// go -- and "stay where you happen to be" lands on the first of them, because
/// it is also the address every chainload bounces through.
///
/// What is left is the map. The seed is the middle of the biggest run of RAM
/// this title has never been seen using; with no map at all that is the middle
/// of the relocatable window, which is a guess and is logged as one.
fn base_for_low_preset(
    loaders: &loaders::LoaderSet,
    boot: &[u8],
    address: u32,
    seen: Option<&memmap::MemoryMap>,
    sp_min: Option<u32>,
) -> Option<u32> {
    // FROM THE END OF THIS TITLE'S OWN IMAGE, not from the constant floor. For a
    // title whose preset cannot be honoured, that constant is exactly what has
    // to give: Jet Set Radio leaves one 64 KB block above 0x8ce00000, with its
    // own data hard against both sides of it, and 12.4 MB below.
    let image_end = ((address & 0x1fff_ffff) | 0x8c00_0000).saturating_add(boot.len() as u32);
    let (lo, hi) = loaders::window_above_image(image_end);
    let map = seen.copied().unwrap_or_default();
    let (run_lo, run_hi, seed) = map
        .free_runs(lo, hi)
        .into_iter()
        .find_map(|(a, b)| loaders::base_in_span(a, b).map(|s| (a, b, s)))?;
    info!(
        "this title's image ends at 0x{image_end:08x}, so a loader may go anywhere from \
         0x{lo:08x} up; the biggest stretch of that no disc read has ever landed in is \
         0x{run_lo:08x}..0x{run_hi:08x} ({} KB), and its middle is 0x{seed:08x}",
        (run_hi - run_lo) / 1024
    );
    for margin in [0x4_0000u32, 0] {
        let is_clear = |b: u32| {
            !loaders::ruled_out_by_low_preset(b)
                && base_is_clear(loaders, boot, address, b, seen, sp_min, margin)
        };
        let clear: Vec<u32> = loaders
            .available()
            .into_iter()
            .filter(|&b| is_clear(b))
            .collect();
        // A base someone linked and ran outranks one this pass merely believes
        // in -- the same order `choose` uses, and for the same reason.
        if clear.contains(&seed) {
            return Some(seed);
        }
        if let Some(built) = loaders::nearest_clear_base(seed, &clear) {
            return Some(built);
        }
        if loaders.relocatable().is_some()
            && let Some(found) = loaders::search_free_base_above(lo, seed, is_clear)
        {
            return Some(found);
        }
    }
    None
}

/// The pre-built set first, then relocation -- for whatever "clear" means to
/// the caller.
fn choose(
    loaders: &loaders::LoaderSet,
    wanted: u32,
    is_clear: &dyn Fn(u32) -> bool,
) -> Option<u32> {

    // THE PRE-BUILT SET FIRST. Relocation answers what it cannot.
    //
    // Three measurements on Sonic Adventure 2, whose preset is 0x8cfe8000,
    // settle this — and the middle one is why "nearest to the preset" is NOT
    // the rule, though it was for an afternoon:
    //
    //   0x8cef8000  the game and its Kart mode both run
    //   0x8cfd0000  freezes loading COURSE.PVM, the Kart's track textures,
    //               which it decompresses into ~0x8cfc0000..0x8cfc6000 —
    //               41 KB under that base
    //   0x8ce00000  Kart is a black screen; it streams KART.ADX into
    //               0x8ce3a920, 182 KB above that base
    //
    // Being near the preset is worth nothing on its own: DreamShell picked
    // 0x8cfe8000 for isoldr, whose network build is 13 KB and fits the 32 KB
    // hole between the title's texture buffers and its Maple DMA list. Ours
    // needs 56 KB and does not fit that hole at all, so "just below the preset"
    // lands in the texture buffers and "well below" lands in the audio heap.
    // 0x8cef8000 works because it is in neither — and the only reason anyone
    // knows that is that someone ran it.
    //
    // So a base someone linked and ran outranks one this pass merely believes
    // in, and the constant scan's blind spot is exactly why: it sees addresses
    // a title NAMES, and every failure above was an allocator, which names
    // none. `receive_syscalls` reports how close reads actually come, which is
    // the evidence this choice cannot have in advance.
    let clear: Vec<u32> = loaders.available().into_iter().filter(|&b| is_clear(b)).collect();
    if let Some(built) = loaders::nearest_clear_base(wanted, &clear) {
        return Some(built);
    }
    // SAME FAMILY IN THE RELOCATION BRANCH TOO, not just in `nearest_clear_base`.
    // `search_free_base` walks a window that is entirely high, so without this a
    // low `wanted` is answered with a high base -- which is the collision a low
    // preset exists to avoid. Sonic Adventure is the case: preset 0x8c004000,
    // and a map marking 0x8ce00000..0x8cef0000. This used to be a consequence of
    // relocation being unable to produce a low image at all; it now stands on
    // its own, and is the only thing keeping the families apart here.
    if !loaders::is_high(wanted) {
        return None;
    }
    loaders
        .relocatable()
        .is_some()
        .then(|| loaders::search_free_base(wanted, is_clear))
        .flatten()
        .filter(|&b| b != wanted)
}

fn wanted_loader_base(
    args: &Args,
    running: Option<u32>,
    disc: Option<(&dyn disc_formats::types::DiscFormat, &str)>,
) -> Option<u32> {
    if args.no_relocate {
        return None;
    }
    if let Some(base) = args.loader_base {
        info!("loader base 0x{base:08x} (from --loader-base)");
        return Some(base);
    }
    let (disc, disc_path) = disc?;

    let identity = match dispatch::identify(disc, disc_path) {
        Ok(id) => id,
        Err(reason) => {
            // A warning, not a debug line, and it carries the reason. This is
            // the last point at which a bad `-d` path is cheap to notice: the
            // run continues, the title is uploaded, and every disc read it
            // makes afterwards fails.
            warn!("{reason}");
            warn!("cannot choose a loader base for this title; keeping the loader where it is");
            return None;
        }
    };
    info!(
        "disc: {} [{} {} {}] boot-sector md5 {}",
        identity.title, identity.product, identity.version, identity.region, identity.md5
    );

    let loaders = loaders::LoaderSet::discover(args.loader_dir.clone());
    let (db_path, db_searched) = game_db_path(args, &loaders);

    let db = match presets::PresetDb::load(&db_path) {
        Ok(db) => db,
        Err(e) => {
            warn!(
                "no game database at {} ({e}); every title will run at the loader's \
                 current address. Generate it with dcload-ip's scripts/make-preset-db.py \
                 and put game-presets.tsv in this project's root. Looked in: {}.",
                db_path.display(),
                db_searched
            );
            return None;
        }
    };
    debug!("game database: {} rows from {}", db.len(), db_path.display());

    // NOT AN EARLY RETURN ANY MORE. "Not in the database" used to mean "keep the
    // loader where it is", decided without ever looking at where that was -- and
    // where it is need not be the stock base: a chainload leaves the loader
    // wherever the last title needed it, and the next title inherits that. The
    // answer is worked out below with the boot binary and the map in hand, like
    // every other one.
    let found = db.lookup(&identity);
    if found.is_none() {
        info!(
            "'{}' is not in the game database ({} rows); nothing prescribes an address \
             for it",
            identity.title,
            db.len()
        );
    }
    if let Some((preset, kind)) = &found {
        // The whole row, once, for anyone reconstructing a session from the log.
        // `dma` and `fastboot` describe DreamShell's own storage device and menu
        // and mean nothing on a network transport; `async` is isoldr's sectors-per
        // -request, which dcload fixes at 8 (GD_EMU_ASYNC) at build time.
        debug!(
            "preset: memory={:08x} async={} dma={} irq={} cdda={:08x} heap={:08x} \
             low={} fastboot={} type={} mode={} altread={}",
            preset.memory, preset.emu_async, preset.dma, preset.irq, preset.cdda,
            preset.heap, preset.low, preset.fastboot, preset.bin_type,
            preset.boot_mode, preset.altread
        );

        match kind {
            presets::MatchKind::BootSectorMd5 => info!(
                "matched '{}' exactly (boot-sector md5): loader wants 0x{:08x}",
                preset.title, preset.memory
            ),
            presets::MatchKind::Title => {
                let ambiguity = db.title_ambiguity(&identity.title);
                if ambiguity > 1 {
                    warn!(
                        "matched '{}' BY TITLE ONLY, and presets under that title disagree \
                         about the address ({} different values); using 0x{:08x}. Pin it with \
                         --loader-base if this dump misbehaves.",
                        preset.title, ambiguity, preset.memory
                    );
                } else {
                    info!(
                        "matched '{}' by title (this exact dump is not in the database): \
                         loader wants 0x{:08x}",
                        preset.title, preset.memory
                    );
                }
            }
        }

        // Say what the preset asked for that this host does not do. When a title
        // misbehaves, "its preset wanted interrupt hooking and we dropped it" is
        // the first thing worth knowing, and it is invisible otherwise.
        for note in preset.unsupported() {
            warn!("'{}': not honoured -- {}", preset.title, note);
        }
    }

    // A PRESET CAN ASK FOR A BASE THE TITLE ITSELF WRITES TO.
    //
    // DreamShell's addresses are chosen for isoldr, whose network build is
    // 13 KB; ours reserves 0xe000 from the base for image, stack, packet
    // buffers and Maple buffer, so a base that leaves isoldr room can leave us
    // none. Sonic Adventure 2 is the measured case: preset 0x8cfe8000, and its
    // own Maple DMA list at 0x8cff0000, which is our stack. The console then
    // goes quiet with nothing logged at either end -- the DMA is written by the
    // hardware, so neither dcload nor this host is in the path (AGENTS.md 4.12
    // has the other cause with the same silence). 0x8cef8000 runs it perfectly.
    //
    // Checked here, from the disc's own boot binary, because this is the last
    // moment the base can still be changed: the relocation happens before the
    // title is uploaded. It re-reads the boot binary that `resolve_payload`
    // will read again -- a megabyte or two, against a session that would end in
    // a black screen with no way to tell why.
    let framed_wince;
    let boot = match disc_formats::boot::extract(disc, args.descramble.into(), args.wince_mode()) {
        Ok(b) => {
            framed_wince = b.wince && b.skipped > 0;
            b.bytes
        }
        Err(e) => {
            // Not fatal, and not silent: the base stands, and if it does
            // collide this line is the only warning there will ever be. A
            // preset this host cannot build is no better than none here --
            // without the binary there is nothing to choose a substitute with.
            let unchecked = found
                .as_ref()
                .map(|(p, _)| p.memory)
                .filter(|&m| loaders::known_unsupported(m).is_none());
            match unchecked {
                Some(m) => warn!(
                    "could not read the boot binary to check it against the loader's \
                     address ({e}); using 0x{m:08x} unchecked"
                ),
                None => warn!(
                    "could not read the boot binary to check it against the loader's \
                     address ({e}); leaving the loader where it is, unchecked"
                ),
            }
            return unchecked;
        }
    };

    // A WINDOWS CE TITLE SAYS WHERE ITS RAM IS, AND IT IS ALMOST ALL OF IT.
    // Its kernel hands pages out of `ulRAMStart..ulRAMEnd` from the top down,
    // so a loader placed by the rules below -- which know Katana allocators --
    // lands in that pool and is overwritten once CE's allocations reach it.
    // The loader goes at the top of the pool instead, and the upload tells CE
    // its pool ends there (`wince::ram_end_patch`). Measured on Sega Rally 2
    // PAL: pool 0x8c143000..0x8cef0000, loader at 0x8cee0000.
    if framed_wince {
        match wince::romhdr(&boot, args.address) {
            Some(h) => match wince::loader_base(&h, loaders::LOADER_SPAN) {
                Some(base) => {
                    info!(
                        "Windows CE: its kernel manages RAM 0x{:08x}..0x{:08x} (ROMHDR at                          0x{:08x}); putting the loader at 0x{base:08x}, the top of that, and                          telling CE its RAM ends there",
                        h.ram_start, h.ram_end, h.at
                    );
                    return Some(base);
                }
                None => warn!(
                    "Windows CE: its RAM ends at 0x{:08x}, too low to take the loader's 64 KB                      out of; placing the loader by the usual rules, where CE may reuse it",
                    h.ram_end
                ),
            },
            None => warn!(
                "Windows CE: no ROM header found in the boot image, so where CE's kernel                  keeps its RAM is unknown; placing the loader by the usual rules, where CE                  may reuse it"
            ),
        }
    }

    // WHICH ADDRESSES WERE ON THE TABLE, not just the one that won. Measured
    // 2026-08-27: a run picked 0x8ce00000 when the policy says 0x8cef8000,
    // because the loader set it was reading did not have the latter -- and the
    // log gave no way to tell. The set is deployed by hand (AGENTS.md 16), so
    // "which loaders were actually there" is a real question with a silent
    // wrong answer.
    //
    // AND IT MUST COUNT THE RELOCATABLE IMAGE, which is the whole set today.
    // This listed pre-linked `dcload-0x<base>.elf` files only, so once
    // LOADER_BASES was emptied (2026-09-04) it reported "none" for every
    // directory including the ones it was about to load from -- a line whose
    // entire purpose is to answer "which loaders were actually there" giving
    // the one answer that is never right. "none" now means nothing is there.
    info!("loader candidates in {}: {}", loaders.dir().display(), {
        let mut parts: Vec<String> = loaders
            .available()
            .iter()
            .map(|b| format!("0x{b:08x}"))
            .collect();
        if loaders.relocatable().is_some() {
            parts.push("relocatable (any base)".to_string());
        }
        if parts.is_empty() {
            "none -- no dcload-0x<base>.elf and no dcload-relocatable.elf; \
             run `make loaders` and copy them here"
                .to_string()
        } else {
            parts.join(", ")
        }
    });
    let memory_path = memory_db_path(args, &loaders);
    let seen_db = memmap::MemoryDb::load(&memory_path);
    let seen = seen_db.get(&identity.md5).map(|r| r.map);
    // THE OTHER HALF OF WHAT EARLIER SESSIONS MEASURED. The bitmap says where
    // this title's reads landed; this says how deep its stack went, which is
    // the only evidence there is about whether a loader may sit under it.
    // `None` until some session has read it back off the console.
    let sp_min = seen_db.get(&identity.md5).and_then(|r| r.sp_min);
    if let Some(sp) = sp_min {
        info!(
            "this title has been seen entering GD syscalls with a stack pointer as low \
             as 0x{sp:08x}"
        );
    }
    match seen.as_ref() {
        Some(m) => info!(
            "memory map: this title has been seen using {} of 256 blocks of RAM ({}, {} games)",
            m.blocks_marked(),
            memory_path.display(),
            seen_db.len()
        ),
        None => info!(
            "memory map: nothing recorded for this game yet ({}, {} games); \
             this session will start one",
            memory_path.display(),
            seen_db.len()
        ),
    }
    // NOTHING IN THE DATABASE PRESCRIBES AN ADDRESS, SO THE LOADER STAYS -- BUT
    // "STAYS" IS A DECISION, and this is the first point at which this host
    // checks it. It used to be taken before the boot binary or the map had been
    // read, on the assumption that where the loader is, is the stock base; a
    // chainload leaves it wherever the last title needed it, and 0x8ce00000 is
    // where every chainload passes through.
    let Some((preset, _)) = &found else {
        let running = running?;
        // A low loader this set cannot reproduce (the CD's own, once the set
        // outgrew the low family) would be kept as it is, older build and all:
        // go high instead, like a painted title.
        let unprovidable = !loaders::is_high(running) && !loaders.can_provide(running);
        if !unprovidable && base_is_clear(
            &loaders,
            &boot,
            args.address,
            running,
            seen.as_ref(),
            sp_min,
            0x4_0000,
        ) {
            info!("keeping the loader where it is, at 0x{running:08x}");
            return None;
        }
        // A LOW-FAMILY VERDICT GOES TO THE HIGH FAMILY, as it does for a preset.
        // `pick_clear_base` never crosses families, so from the stock base it
        // found nothing and the loader stayed where Snow Surfers paints its
        // stack (2026-09-17).
        let painted = low_loader_painted_by_title(&loaders, &boot, args.address, running);
        if painted.is_some()
            || unprovidable
            || !low_base_has_stack_headroom(&loaders, running, sp_min)
        {
            match painted {
                Some(p) => warn!(
                    "'{}' is not in the database, and {}. Leaving the low family.",
                    identity.title,
                    painted_reason(running, p)
                ),
                None if unprovidable => warn!(
                    "'{}' is not in the database, and the loader set cannot be placed at \
                     0x{running:08x}, where the running loader is: its image no longer fits \
                     under the BIOS VBR. Leaving the low family.",
                    identity.title
                ),
                None => warn!(
                    "'{}' is not in the database, and its stack has been measured coming \
                     within {} bytes of a loader at 0x{running:08x}. Leaving the low family.",
                    identity.title,
                    loaders::LOW_BASE_MIN_MARGIN
                ),
            }
            let alt = base_off_the_low_family(
                &loaders,
                &boot,
                args.address,
                seen.as_ref(),
                sp_min,
                loaders::SCRATCH_BASE,
            );
            if alt.is_none() {
                error!(
                    "'{}': nothing clear of the low family could be produced, so the loader \
                     stays at 0x{running:08x}, where this title overwrites it.",
                    identity.title
                );
            }
            return alt;
        }
        warn!(
            "'{}' is not in the database, and 0x{running:08x} -- where the loader \
             already is -- is RAM this title addresses or has been seen reading into. \
             Looking for somewhere else.",
            identity.title
        );
        return pick_clear_base(
            &loaders,
            &boot,
            args.address,
            running,
            seen.as_ref(),
            sp_min,
        );
    };

    // A PRESET THIS HOST CANNOT BUILD IS THE STRONGEST STATEMENT IN THE
    // DATABASE, NOT A MISSING ONE.
    //
    // It used to end the decision: `ensure_loader_base` refused the address and
    // kept the loader where it was. That is the one answer the preset positively
    // excludes -- DreamShell went below the BIOS syscall area only after
    // 0x8ce00000 and 0x8cfe8000 had both failed for this title, and 0x8ce00000
    // is exactly where a loader that has been chainloaded is sitting.
    //
    // Measured 2026-08-28 on Jet Set Radio (preset 0x8c000100): the host stayed
    // at 0x8ce00000, the constant scan reported the title loading that very
    // address, the run was started anyway, and the 81st disc read of the boot
    // landed on the loader. Nothing had asked whether staying was safe.
    if let Some(reason) = loaders::known_unsupported(preset.memory) {
        warn!(
            "'{}': its preset asks for 0x{:08x}, which this host cannot build -- {reason}. \
             DreamShell puts isoldr below the BIOS syscall area only after its default \
             (0x{:08x}) and its high option (0x{:08x}) have both been rejected for a \
             title, so those two are ruled out here as well.",
            preset.title,
            preset.memory,
            loaders::ISOLDR_DEFAULT_ADDR,
            loaders::ISOLDR_HIGH_ADDR,
        );
        return match base_for_low_preset(&loaders, &boot, args.address, seen.as_ref(), sp_min) {
            Some(alt) => {
                warn!(
                    "'{}': using 0x{alt:08x}, the address furthest from anything this \
                     title is known to touch; pin it with --loader-base to override.",
                    preset.title
                );
                Some(alt)
            }
            None => {
                error!(
                    "'{}': its preset cannot be built and nothing clear of this title \
                     could be produced either. The loader stays where it is: if the \
                     console goes silent with nothing logged, this is why.",
                    preset.title
                );
                None
            }
        };
    }
    let hits = dispatch::literals_in_loader_footprint(&boot, args.address, preset.memory);

    // THE PRESET IS THE ANSWER UNLESS SOMETHING SAYS OTHERWISE, and there are
    // exactly two things that can: what the title NAMES (constants in its
    // binary) and where its reads have LANDED (the learned map). DreamShell's
    // address is isoldr's own answer for this game and is right far more often
    // than any rule of ours -- it is only wrong when our 0xe000 does not fit
    // where isoldr's 13 KB did.
    //
    // The map is consulted for the preset itself, not just for the
    // alternatives. It used to be checked only after the constant scan had
    // already rejected the preset, which meant a game whose map said "the
    // preset is in the middle of my texture buffers" was sent there anyway --
    // the one case where the map has something to say and nothing to say it
    // about.
    // THE SAME TEST AS EVERYWHERE ELSE, which this line was not: it asked the map
    // about a flat span, and so ruled out the stock base for every title that
    // uses low RAM -- all of them.
    let seen_hits_preset = map_hits_loader(preset.memory, seen.as_ref(), 0x4_0000);
    // TWO MORE WAYS A LOW PRESET CAN BE WRONG FOR THIS LOADER, neither of which
    // is an address collision and neither of which the two tests above can see.
    // The first is what the database says about the title; the second is what
    // the console said about it last time. See `low_family_contested` and
    // `low_base_has_stack_headroom`.
    let contested = low_family_contested(&db, &identity, preset);
    let no_headroom = !low_base_has_stack_headroom(&loaders, preset.memory, sp_min);
    let painted = low_loader_painted_by_title(&loaders, &boot, args.address, preset.memory);
    // AND THE SET MAY NOT BE ABLE TO GO THERE AT ALL: a low base needs the
    // image under the BIOS VBR (`LoaderSet::can_provide`).
    let unprovidable = !loaders::is_high(preset.memory) && !loaders.can_provide(preset.memory);
    if hits.is_empty()
        && !seen_hits_preset
        && contested.is_none()
        && !no_headroom
        && painted.is_none()
        && !unprovidable
    {
        return Some(preset.memory);
    }

    // A LOW BASE REFUSED FOR A STACK REASON IS A VERDICT ON THE FAMILY, NOT ON
    // AN ADDRESS. Every base this host can build below 0x8c010000 shares the
    // same 0x8c004000..0x8c00f400 hole with the title's stack, so moving a few
    // kilobytes inside it buys nothing -- which is exactly what the ordinary
    // search would try, since it never crosses families on purpose.
    if contested.is_some() || no_headroom || painted.is_some() || unprovidable {
        if unprovidable {
            warn!(
                "'{}': its preset asks for 0x{:08x}, and the loader set in {} cannot be \
                 placed that low -- its image no longer fits under the BIOS VBR. Leaving the \
                 low family.",
                preset.title,
                preset.memory,
                loaders.dir().display()
            );
        }
        if let Some(p) = painted {
            warn!(
                "'{}': {}. Leaving the low family.",
                preset.title,
                painted_reason(preset.memory, p)
            );
        }
        if let Some(votes) = contested.as_ref() {
            warn!(
                "'{}': the database's presets for this title disagree -- {} -- and one of \
                 them is below the BIOS syscall area. DreamShell only goes there after its \
                 default and its high option have both failed for a title, so that vote is \
                 it saying low RAM was too tight for a loader a quarter of this one's size. \
                 The tie-break picked 0x{:08x} anyway; leaving the low family instead.",
                preset.title,
                votes
                    .iter()
                    .map(|m| format!("0x{m:08x}"))
                    .collect::<Vec<_>>()
                    .join(" and "),
                preset.memory,
            );
        }
        if no_headroom {
            let end = loaders.image_end_for(preset.memory);
            warn!(
                "'{}': this title's stack has been measured reaching 0x{}, and a loader at \
                 0x{:08x} ends at 0x{} -- {} bytes, under the {} this loader's own disc-read \
                 path plus the title's deeper frames need. Nothing here is a guess: the \
                 depth was read off the console in an earlier session. Leaving the low \
                 family.",
                preset.title,
                sp_min.map_or_else(|| "?".into(), |sp| format!("{sp:08x}")),
                preset.memory,
                end.map_or_else(|| "?".into(), |e| format!("{e:08x}")),
                match (sp_min, end) {
                    (Some(sp), Some(e)) => sp.saturating_sub(e).to_string(),
                    _ => "?".to_string(),
                },
                loaders::LOW_BASE_MIN_MARGIN,
            );
        }
        return match base_off_the_low_family(
            &loaders,
            &boot,
            args.address,
            seen.as_ref(),
            sp_min,
            loaders::ISOLDR_HIGH_ADDR,
        ) {
            Some(alt) => {
                warn!(
                    "'{}': using 0x{alt:08x} instead of the preset's 0x{:08x}; pin it with \
                     --loader-base to override.",
                    preset.title, preset.memory
                );
                Some(alt)
            }
            None => {
                error!(
                    "'{}': the low family is ruled out for this title and nothing clear of \
                     it could be produced either. Going ahead at 0x{:08x} anyway: if the \
                     loader stops answering part-way through, this is why.",
                    preset.title, preset.memory
                );
                Some(preset.memory)
            }
        };
    }
    if hits.is_empty() {
        warn!(
            "'{}' has been seen using RAM within 256 KB of 0x{:08x}, the address its preset \
             asks for, though nothing in its binary names it. Looking for somewhere else.",
            preset.title, preset.memory
        );
    } else if let Some((alt, ceiling)) = preset_window_base(
        &loaders,
        &boot,
        args.address,
        preset.memory,
        seen.as_ref(),
        sp_min,
    ) {
        // THE PRESET'S WINDOW, when only our size is the problem. See
        // `preset_window_base`.
        warn!(
            "'{}': its preset 0x{:08x} is where DreamShell's 13 KB loader ran, and the \
             title names 0x{ceiling:08x} just above it (the constant at 0x{:08x}), so a 64 KB \
             loader does not fit there. Using 0x{alt:08x}, against that ceiling: as much of \
             the preset's free window as possible, and nothing the title is known to use. Pin \
             it with --loader-base to override.",
            preset.title,
            preset.memory,
            hits[0].1,
        );
        return Some(alt);
    }
    match pick_clear_base(
        &loaders,
        &boot,
        args.address,
        preset.memory,
        seen.as_ref(),
        sp_min,
    ) {
        Some(alt) => {
            if hits.is_empty() {
                warn!(
                    "'{}': using 0x{alt:08x} instead of the preset's 0x{:08x}, which this \
                     title's own memory map rules out; pin it with --loader-base to override.",
                    preset.title, preset.memory
                );
            } else {
                warn!(
                    "'{}' addresses RAM the loader would occupy at 0x{:08x}: {} constant(s) \
                     point inside it, the first at 0x{:08x} (loaded at 0x{:08x}). A write \
                     there -- and a Maple DMA list is filled by the hardware itself -- \
                     overwrites the loader with no syscall, no packet and no exception. \
                     Using 0x{alt:08x} instead; pin it with --loader-base to override.",
                    preset.title,
                    preset.memory,
                    hits.len(),
                    hits[0].0,
                    hits[0].1,
                );
            }
            Some(alt)
        }
        None => {
            error!(
                "'{}': 0x{:08x} is ruled out ({} constant(s) point into it{}), and nothing \
                 clear of it can be produced. Going ahead there anyway: if the console goes \
                 silent with nothing logged, this is why.",
                preset.title,
                preset.memory,
                hits.len(),
                if seen_hits_preset {
                    ", and its reads have landed nearby"
                } else {
                    ""
                },
            );
            Some(preset.memory)
        }
    }
}

#[derive(Subcommand, Debug)]
enum Commands {
    /// Upload a binary and execute it immediately
    UExec {
        /// What to run: a binary (1ST_READ.BIN, an ELF), or a DISC IMAGE.
        ///
        /// Given an image (.gdi / .cdi / .iso, or a .zip holding one), the boot
        /// binary is read out of it and the same image serves the title's disc
        /// reads -- no extracting anything, and no second path to keep in step.
        #[arg(value_hint = clap::ValueHint::FilePath)]
        file: String,

        /// Path to file to redirect the reads to
        #[arg(short, long, value_hint = clap::ValueHint::FilePath, conflicts_with = "mount")]
        disc: Option<String>,

        #[arg(short, long, value_hint = clap::ValueHint::DirPath)]
        mount: Option<String>,

        /// Enable console redirection
        #[arg(short, long)]
        console: bool,
    },
    /// Upload a binary
    Upload {
        /// Path to file to upload. A disc image works here too: its boot binary
        /// is what gets uploaded.
        #[arg(value_hint = clap::ValueHint::FilePath)]
        file: String,
    },
    /// Scan a disc image's audio tracks for discontinuities. Touches no network.
    ///
    /// Prints the track table, then checks every audio track for large
    /// sample-to-sample steps. Loud music has many, spread evenly; a defect in
    /// the dump or the reader puts them at one offset inside a sector, and only
    /// that is reported as a problem, with the bands of LBAs it occurs in.
    AuditAudio {
        /// Disc image (.gdi / .cdi / .iso / .zip)
        #[arg(value_hint = clap::ValueHint::FilePath)]
        disc: String,

        /// Scan only this track number. Default: every audio track, which on a
        /// GD-ROM is most of the disc and takes a while.
        #[arg(long)]
        track: Option<u8>,
    },
    /// Write a disc image's boot binary out to a file.
    ///
    /// Touches no network. Mostly a way to check what `uexec <image>` is going
    /// to send before sending it -- and the only offline test there is that a
    /// zipped image reads back byte for byte like the loose one.
    Extract {
        /// Disc image (.gdi / .cdi / .iso / .zip)
        #[arg(value_hint = clap::ValueHint::FilePath)]
        disc: String,

        /// Where to write it. Default: the name the disc gives it, in the
        /// current directory.
        #[arg(short, long, value_hint = clap::ValueHint::FilePath)]
        output: Option<String>,
    },
    /// Reboot the console (only works when dcload is in control)
    Reboot {},
    /// Write known patterns to free RAM and read them straight back, across
    /// several sizes and misalignments. Uploads no title and starts nothing --
    /// it only answers "can a read-back off this console be believed at all".
    SelftestReadback {},
    /// Read a disc image and print what it is and which loader base it wants.
    ///
    /// Touches no network and needs no Dreamcast, which is the point: when a
    /// title misbehaves, this separates "the image is not what you think" from
    /// "the console did something odd" in one command.
    Identify {
        /// Disc image (.gdi / .cdi / .iso, or a .zip holding one -- add
        /// `#member` to pick one out of an archive with several)
        #[arg(value_hint = clap::ValueHint::FilePath)]
        disc: String,
    },
    /// Move a relocatable loader ELF to another base and write it out.
    ///
    /// The same relocation `uexec` performs in memory, exposed so it can be
    /// inspected, diffed against a native build, or kept. Needs no Dreamcast
    /// and no SH toolchain.
    Relocate {
        /// The loader to move (loaders/dcload-relocatable.elf)
        #[arg(value_hint = clap::ValueHint::FilePath)]
        elf: String,
        /// Base to move it to, e.g. 0x8cef8000
        #[arg(value_parser = maybe_hex::<u32>)]
        to: u32,
        /// Where to write the result
        #[arg(short, long, value_hint = clap::ValueHint::FilePath)]
        output: String,
    },
}

/// The link's own round-trip time, measured on an idle console.
///
/// The baseline other latencies are read against: the host times its own half
/// of a disc or audio request, and this says what the link adds. One SendBinQ
/// of four bytes, out and back, while the console is idle (after the upload,
/// before EXEC).
///
/// `ping` cannot do this job even though dcload answers ICMP (`net.c`,
/// `process_icmp`): the loader only looks at the wire from inside `bb->loop()`,
/// so once a title is running a reply waits for the next disc or audio fetch --
/// up to 40 ms of the loader's own scheduling, reported as though it were the
/// link.
///
/// FIVE, AND THE MINIMUM IS REPORTED. A UDP round trip has a floor and a tail;
/// the floor is what the link is capable of, and it is the floor a per-fetch
/// cost should be compared with.
fn measure_rtt(conn: &mut DcIoUDP, base: u32) -> Option<std::time::Duration> {
    let mut best: Option<std::time::Duration> = None;

    // START FROM AN EMPTY SOCKET. The console is idle here -- this runs after
    // the upload and the patches and before EXEC, so nothing is waiting on an
    // answer and anything already buffered is a leftover. It is not
    // hypothetical: the PPF patch verification logs "Received non-DBIN packets
    // while waiting for DoneBinary response" immediately before this, and that
    // straggler used to be consumed by the first of these reads, putting all
    // five one answer out of phase and leaving one more behind for whoever read
    // next -- which was verify_image(), and which is what disabled --diag.
    //
    // Draining is safe HERE and nowhere else on this path: while a title runs,
    // a packet from the Dreamcast is a syscall request it is blocked waiting to
    // have answered, and discarding one would freeze it.
    for _ in 0..32 {
        use crate::io::ExternalDcIo as _;
        match conn.poll(Some(std::time::Duration::ZERO)) {
            Ok(evt) if !evt.is_empty() => {
                let _ = conn.handle_data(&evt);
            }
            _ => break,
        }
    }

    for _ in 0..5 {
        let t0 = std::time::Instant::now();
        if dispatch::receive_data(conn, Some(std::time::Duration::from_millis(500)), base, 4, true)
            .is_err()
        {
            continue;
        }
        let dt = t0.elapsed();
        best = Some(best.map_or(dt, |b: std::time::Duration| b.min(dt)));
    }
    best
}

/// Loud when the session asked for the instrument, quiet when it did not.
///
/// `start_diag` runs in every session now, so its "could not" lines would
/// otherwise be a warning about something nobody requested.
fn note(loud: bool, msg: String) {
    if loud {
        warn!("{msg}");
    } else {
        debug!("{msg}");
    }
}

/// Bring up the counter panel, or say why there is none.
///
/// EVERY FAILURE HERE IS A WARNING. This is an instrument bolted onto a session
/// whose actual job is running a game; refusing to start the title because the
/// loader ELF could not be found would be the instrument deciding the outcome
/// of the measurement, which is the trap AGENTS.md 11 keeps coming back to.
///
/// Run BEFORE the title is executed, where a blocking round trip costs nothing
/// and where the log lines it prints are still readable above the panel.
///
/// BUILT IN EVERY SESSION, not only under `--diag`, because `d` can ask for the
/// panel at any moment and none of this can be done once a title is running:
/// the image check below is a blocking round trip, and the console stops
/// answering promptly the moment it has something better to do. Without
/// `--diag` it starts switched off, and every failure here drops to `debug`:
/// nobody asked, so nothing is missing.
/// Where the running loader's GD emulation is entered: `_gd_bios_entry` in the
/// image the host would upload for `base`, which is the one running (a loader
/// that differs from the file is replaced, even at the same base).
fn gd_bios_entry(args: &Args, base: u32) -> Result<u32, String> {
    let (elf, label) = loaders::LoaderSet::discover(args.loader_dir.clone()).image_for(base)?;
    loaders::symbols(&elf)?
        .get("gd_bios_entry")
        .map(|&(addr, _)| addr)
        .ok_or_else(|| format!("{label} predates it"))
}

/// The running loader's staging buffers for reads into translated addresses
/// (`_gd_stage` in `.hiram`, `_gd_stage_big` above `_end`; dcload-ip
/// cdfs_syscalls.c): the ranges of the loader a disc read is meant to land on.
/// Empty for a loader that predates them.
fn loader_stage(args: &Args, base: u32) -> Vec<(u32, u32)> {
    let Ok((elf, _)) = loaders::LoaderSet::discover(args.loader_dir.clone()).image_for(base) else {
        return vec![];
    };
    let Ok(syms) = loaders::symbols(&elf) else {
        return vec![];
    };
    ["gd_stage", "gd_stage_big"]
        .iter()
        .filter_map(|n| syms.get(*n).copied())
        .filter(|&(_, n)| n > 0)
        .collect()
}

fn start_diag(
    args: &Args,
    conn: &mut DcIoUDP,
    running_base: Option<u32>,
    recorder: Option<std::sync::Arc<std::sync::Mutex<memmap::MemoryRecorder>>>,
) -> Option<diag::Probe> {
    let asked = args.diag;
    let Some(base) = running_base else {
        note(
            asked,
            "--diag needs a loader that reports its own load address, and this one \
             does not: without it there is no way to know which ELF the counters \
             live in. Rebuild dcload-ip and re-burn its boot image."
                .into(),
        );
        return None;
    };
    let loaders = loaders::LoaderSet::discover(args.loader_dir.clone());
    // The SAME image the host would upload for this base -- a pre-linked ELF
    // when the set has one, otherwise the relocatable one moved in memory,
    // which reproduces a native link byte for byte. That is what makes the
    // comparison below meaningful for a relocated loader, where there is no ELF
    // on disk to aim an external tool at.
    let (elf, label) = match loaders.image_for(base) {
        Ok(v) => v,
        Err(e) => {
            note(
                asked,
                format!("--diag: no loader ELF to read the counter addresses out of: {e}"),
            );
            return None;
        }
    };
    if let Err(e) = diag::verify_image(conn, &elf, &label) {
        note(asked, format!("--diag disabled: {e}"));
        return None;
    }
    let interval = std::time::Duration::from_secs_f64(args.diag_interval.clamp(0.25, 30.0));
    match diag::Probe::new(&elf, label, interval, asked) {
        Ok(mut probe) => {
            // The panel's range contains the two stack counters, so it is the
            // one that reads them while it is up -- see `Probe::stack`.
            match stackwatch::StackVerdict::from_elf(&elf, base, recorder) {
                Ok(v) => probe.watch_stack(v),
                Err(e) => debug!("--diag: no stack verdict from this loader: {e}"),
            }
            // The connection claims the replies, not the syscall loop: they
            // arrive inside whatever transfer is polling at the time. See
            // `diag::SampleSink`.
            probe.install(conn);
            let (lo, span) = probe.span();
            if asked {
                info!(
                    "diag: {} counters from {} (image verified), {span} bytes at \
                     0x{lo:08x} every {:.1} s -- d to stop",
                    probe.counter_count(),
                    probe.label(),
                    interval.as_secs_f64(),
                );
            } else {
                info!(
                    "diag: {} counters ready from {} -- press d to sample them",
                    probe.counter_count(),
                    probe.label(),
                );
            }
            Some(probe)
        }
        Err(e) => {
            note(asked, format!("--diag disabled: {e}"));
            None
        }
    }
}

/// Bring up the stack watch, or say why there is none.
///
/// EVERY FAILURE IS A WARNING, never a refusal to run the title -- the same
/// rule as the counter panel. This is an instrument, and an instrument that
/// decides whether the session happens is the trap AGENTS.md 11 keeps coming
/// back to.
///
/// The image is verified against the running loader first, and that check is
/// not a formality: two builds at the same base put the same counter at
/// different addresses (AGENTS.md 14.19), so an unverified watch reports a
/// believable number about the wrong memory. Run before `execute`, where a
/// blocking round trip costs nothing.
fn start_stack_watch(
    args: &Args,
    conn: &mut DcIoUDP,
    running_base: Option<u32>,
    recorder: Option<std::sync::Arc<std::sync::Mutex<memmap::MemoryRecorder>>>,
) -> Option<stackwatch::StackWatch> {
    let Some(base) = running_base else {
        // An older loader that does not report where it was linked. Nothing to
        // aim at, and probing for it would cost more round trips than the
        // measurement is worth here.
        debug!("no stack watch: this loader does not report its own load address");
        return None;
    };
    let loaders = loaders::LoaderSet::discover(args.loader_dir.clone());
    let (elf, label) = match loaders.image_for(base) {
        Ok(v) => v,
        Err(e) => {
            debug!("no stack watch: no loader ELF to read the counter addresses out of: {e}");
            return None;
        }
    };
    if let Err(e) = diag::verify_image(conn, &elf, &label) {
        warn!(
            "no stack watch: {e}. This session cannot tell how close this title's stack \
             comes to the loader, and nothing will be learned for the next one."
        );
        return None;
    }
    match stackwatch::StackWatch::new(&elf, base, recorder) {
        Ok(watch) => {
            watch.install(conn);
            debug!("stack watch: reading the GD stack counters out of {label}");
            Some(watch)
        }
        Err(e) => {
            debug!("no stack watch: {e}");
            None
        }
    }
}

/// Tell the loader the title is a KOS binary (`g_gd_kos`, cdfs_syscalls.c):
/// its disc reads then start without the first yield, as isoldr does for
/// BIN_TYPE_KOS. KOS polls a DMA read once and, on PROCESSING, sleeps until
/// an interrupt nothing raises; only its vblank handler then moves the read,
/// from inside the interrupt. Never fatal: a loader without the symbol keeps
/// the yield, and the log says so.
fn tell_loader_kos(args: &Args, conn: &mut DcIoUDP, running_base: Option<u32>) -> bool {
    let Some(base) = running_base else {
        warn!("KOS title: the loader does not report its base, so it cannot be told");
        return false;
    };
    let loaders = loaders::LoaderSet::discover(args.loader_dir.clone());
    let addr = loaders
        .image_for(base)
        .map_err(|e| e.to_string())
        .and_then(|(elf, _)| loaders::symbols(&elf))
        .and_then(|syms| {
            syms.get("g_gd_kos")
                .map(|&(addr, _)| addr)
                .ok_or_else(|| "this loader has no g_gd_kos (an older build)".to_string())
        });
    match addr {
        Ok(addr) => {
            info!(
                "KOS title: the loader starts its disc reads at once and takes its console \
                 (g_gd_kos at 0x{addr:08x})"
            );
            match dispatch::apply_patches(conn, &[(addr, 1)]) {
                Ok(()) => true,
                Err(e) => {
                    warn!("could not set g_gd_kos: {e}");
                    false
                }
            }
        }
        Err(e) => {
            warn!(
                "KOS title, but {e}: its disc reads will wait for KOS's vblank, from inside \
                 the interrupt"
            );
            false
        }
    }
}

/// Lower a KOS title's top of RAM under the loader (`kos_mem_top_patches`):
/// its heap and main stack otherwise reach 0x8cff0000..0x8d000000, through a
/// high loader and through a low one's buffers. Never fatal.
fn lower_kos_mem_top(conn: &mut DcIoUDP, running_base: Option<u32>, boot: &[u8], address: u32) {
    let Some(base) = running_base else {
        warn!("KOS title: the loader does not report its base; its top of RAM is left alone");
        return;
    };
    let p1 = |a: u32| (a & 0x1fff_ffff) | 0x8c00_0000;
    let load = p1(address);
    // The lowest part of the loader above the title: the whole span of a high
    // loader, the Maple/.hiram buffers of a low one.
    let Some(top) = loaders::live_footprint(base)
        .into_iter()
        .map(|(start, _)| p1(start))
        .filter(|&start| start > load)
        .min()
    else {
        return;
    };
    match dispatch::kos_mem_top_patches(boot, load, top) {
        Ok(patches) => {
            info!(
                "KOS title: top of RAM lowered from 0x8d000000 to 0x{top:08x}, under the \
                 loader -- heap up to 0x{:08x}, {} KB less RAM",
                top - 0x1_0000,
                (0x8d00_0000 - top) / 1024
            );
            if let Err(e) = dispatch::apply_patches(conn, &patches) {
                warn!("could not lower the KOS top of RAM: {e}");
            }
        }
        Err(e) => warn!(
            "KOS title, but {e}: its heap and stack may reach the loader at 0x{base:08x}"
        ),
    }
}

/// Paint the witness words and bring up their check, or say why not
/// (`src/marks.rs`). Never fatal, like every instrument here.
fn start_marks(
    args: &Args,
    conn: &mut DcIoUDP,
    running_base: Option<u32>,
    wince: bool,
    image_end: u32,
    recorder: Option<std::sync::Arc<std::sync::Mutex<memmap::MemoryRecorder>>>,
) -> Option<marks::MarkWatch> {
    if args.no_marks {
        return None;
    }
    // Nothing to learn into: a title with no identity records nothing.
    let recorder = recorder?;
    let Some(base) = running_base else {
        debug!("no memory marks: this loader does not report its own load address");
        return None;
    };
    if wince {
        debug!("no memory marks: Windows CE's kernel owns this RAM, and its loader's place is fixed");
        return None;
    }
    let known = recorder.lock().ok()?.known();
    let blocks = marks::blocks_to_paint(image_end, base, &known);
    if blocks.is_empty() {
        return None;
    }
    let t = std::time::Instant::now();
    match marks::paint(conn, &blocks) {
        Ok(()) => {
            info!(
                "memory marks: {} blocks of 64 KB above the title's image painted in {:.0} ms; \
                 the ones it writes will be recorded as used",
                blocks.len(),
                t.elapsed().as_secs_f64() * 1e3
            );
            let watch = marks::MarkWatch::new(blocks, recorder);
            watch.install(conn);
            Some(watch)
        }
        Err(e) => {
            warn!("memory marks: {e}; this session learns from disc reads only");
            None
        }
    }
}

/// `identify`: everything the loader-placement pass would work out, printed.
fn identify_only(args: &Args, disc: &str) -> ExitCode {
    let reader = match dispatch::open_disc(disc) {
        Ok(d) => d,
        Err(reason) => {
            error!("{reason}");
            return ExitCode::FAILURE;
        }
    };
    let identity = match dispatch::identify(reader.as_ref(), disc) {
        Ok(id) => id,
        Err(reason) => {
            error!("{reason}");
            return ExitCode::FAILURE;
        }
    };
    println!("title    : {}", identity.title);
    println!("product  : {} {}", identity.product, identity.version);
    println!("region   : {}", identity.region);
    println!("boot md5 : {}", identity.md5);
    // WHAT THE DISC CAN PLAY, which is not derivable from anything else printed
    // here. A title only ever learns it has music from the table of contents,
    // so "how many audio tracks does this image have" is the first thing worth
    // knowing about a title that is supposed to have a soundtrack and does not.
    let tracks = reader.toc_tracks();
    if tracks.is_empty() {
        println!("tracks   : this image does not enumerate its tracks -- no CDDA possible");
    } else {
        let audio: Vec<u8> = tracks.iter().filter(|t| t.audio).map(|t| t.number).collect();
        if audio.is_empty() {
            println!("tracks   : {} tracks, none of them audio", tracks.len());
        } else {
            println!(
                "tracks   : {} tracks, {} audio ({})",
                tracks.len(),
                audio.len(),
                audio
                    .iter()
                    .map(|n| n.to_string())
                    .collect::<Vec<_>>()
                    .join(",")
            );
        }
    }
    let mut framed_wince = false;
    let boot_bytes = match disc_formats::boot::extract(
        reader.as_ref(),
        args.descramble.into(),
        args.wince_mode(),
    ) {
        Ok(b) => {
            framed_wince = b.wince && b.skipped > 0;
            println!(
                "boot bin : {} ({} bytes at LBA {}){}",
                b.name,
                b.bytes.len(),
                b.lba,
                match (b.scrambling, b.descrambled) {
                    (_, true) => " -- unscrambled",
                    (disc_formats::scramble::Scrambling::Plain, _) => " -- plain",
                    _ => "",
                }
            );
            println!("bin md5  : {:x}", md5::compute(&b.bytes));
            if b.wince {
                println!(
                    "wince    : Windows CE -- {}",
                    if args.no_wince {
                        "uploaded whole and entered directly (--no-wince)".to_string()
                    } else {
                        format!(
                            "first {} bytes dropped as isoldr does, entered through the \
                             disc's own second bootstrap",
                            b.skipped
                        )
                    }
                );
            }
            Some(b.bytes)
        }
        Err(e) => {
            println!("boot bin : NOT FOUND -- {e}");
            None
        }
    };
    if let Some(b) = boot_bytes.as_ref() {
        let n = dispatch::gd_body_patches(b, args.address, 0).len();
        if n > 0 {
            println!(
                "gd body  : {n} direct call site(s) to the BIOS GD driver (0x8c0010f0), \
                 pointed at the loader's emulation at upload"
            );
        }
        if framed_wince {
            match wince::romhdr(b, args.address) {
                Some(h) => println!(
                    "ce ram   : ROMHDR at 0x{:08x}: RAM 0x{:08x}..0x{:08x}, driver globals \
                     0x{:08x}..0x{:08x}; loader {}",
                    h.at,
                    h.ram_start,
                    h.ram_end,
                    h.drivglob_start,
                    h.drivglob_start.wrapping_add(h.drivglob_len),
                    match wince::loader_base(&h, loaders::LOADER_SPAN) {
                        Some(base) => format!("at 0x{base:08x}, RAM end moved there"),
                        None => "placed by the usual rules".to_string(),
                    }
                ),
                None => println!("ce ram   : no ROM header found"),
            }
            match wince::pio_patches(b, args.address).first() {
                Some((at, w)) => println!(
                    "ce gd    : aligned reads sent to PIO at 0x{at:08x} (word 0x{w:08x})"
                ),
                None => println!("ce gd    : DMA/PIO choice NOT found -- DMA streams would stall"),
            }
        }
    }

    // WHAT --vga WOULD DO, answered where it costs no console. "The cable check
    // was not found" is the one thing worth knowing BEFORE such a run: after
    // it, a title that ignored the patch and a title that was never patched
    // look exactly the same from here.
    let declared = disc_formats::types::find_ip_bin(reader.as_ref())
        .and_then(|sector| dispatch::ip_bin_peripherals(&sector))
        .map(|p| p & dispatch::PERIPHERAL_VGA != 0);
    let cable = boot_bytes
        .as_deref()
        .map(|b| dispatch::vga_cable_patches(b, args.address))
        .unwrap_or_default();
    println!(
        "vga      : IP.BIN {}; {}",
        match declared {
            Some(true) => "declares VGA box support",
            Some(false) => "does NOT declare VGA box support",
            None => "has no readable peripheral field",
        },
        match cable.len() {
            0 => "no cable check found, so --vga can patch no code".to_string(),
            n => format!("{n} cable check(s) --vga can force to VGA"),
        }
    );

    // WHAT THE PATCH LIBRARY WOULD DO, and the one place it can be checked for
    // free. A PPF that does not fit is a fact about two files and nothing else,
    // so finding it out here costs a command; finding it out on hardware costs
    // a title that boots and then behaves strangely, which is the hardest thing
    // in this project to attribute to anything.
    match boot_bytes.as_deref() {
        Some(boot) => {
            let plan = patch_plan(args, boot, Some(&identity.md5));
            let line = |c: &patchdb::Chosen, what: &str| {
                let mut out = format!("{what} {}", c.describe());
                if let Some(first) = c.note.lines().map(str::trim).find(|l| !l.is_empty()) {
                    out.push_str(&format!("\n           {first}"));
                }
                out
            };
            let mut said = false;
            for c in &plan.apply {
                println!("patch    : {}", line(c, "WOULD APPLY"));
                said = true;
            }
            for c in &plan.offer {
                println!("patch    : {}", line(c, "available (--ppf)"));
                said = true;
            }
            for p in &plan.problems {
                println!("patch    : {p}");
                said = true;
            }
            if !said {
                println!(
                    "patch    : no PPF patch listed or found for this dump ({})",
                    plan.summary
                );
            }
        }
        None => println!("patch    : no boot binary, so no PPF patch could be checked"),
    }

    let loaders = loaders::LoaderSet::discover(args.loader_dir.clone());

    // Does the title address the RAM the loader would be sitting in? Answered
    // HERE because it needs no console: a collision found offline costs one
    // command, and the same collision found on hardware costs a session that
    // ends with a black screen and nothing logged (see
    // `literals_in_loader_footprint`).
    // The same memory `uexec` would consult, so the offline report answers with
    // what a run would actually pick.
    let seen_db = memmap::MemoryDb::load(&memory_db_path(args, &loaders));
    let seen = seen_db.get(&identity.md5).map(|r| r.map);
    let sp_min = seen_db.get(&identity.md5).and_then(|r| r.sp_min);
    match seen.as_ref() {
        Some(m) => println!(
            "seen     : {} of 256 blocks of 64 KB used in earlier sessions \
             (of {} games recorded)",
            m.blocks_marked(),
            seen_db.len()
        ),
        None => println!(
            "seen     : nothing recorded for this game yet (of {} games recorded)",
            seen_db.len()
        ),
    }
    // The third placement test, and the one nothing else here can stand in for:
    // how deep this title's stack has been measured going. See
    // `low_base_has_stack_headroom`.
    match sp_min {
        Some(sp) => {
            let end = loaders.image_end_for(loaders::DEFAULT_BASE);
            println!(
                "stack    : enters GD syscalls as low as 0x{sp:08x}; a loader at \
                 0x{:08x} ends at 0x{} -- {} (needs {})",
                loaders::DEFAULT_BASE,
                end.map_or_else(|| "?".into(), |e| format!("{e:08x}")),
                match end {
                    Some(e) => format!("{} bytes under it", sp.saturating_sub(e)),
                    None => "no loader image to measure against".to_string(),
                },
                loaders::LOW_BASE_MIN_MARGIN,
            )
        }
        None => println!(
            "stack    : never measured -- no session has read this title's GD stack \
             pointer back off the console"
        ),
    }
    // What the title writes before it calls anything, which the stack line
    // above cannot see. See `low_loader_painted_by_title`.
    let painted_at = |base: u32| {
        boot_bytes
            .as_deref()
            .and_then(|b| low_loader_painted_by_title(&loaders, b, args.address, base))
    };
    if let Some(bytes) = boot_bytes.as_deref() {
        let fills = dispatch::constant_range_fills(bytes, args.address);
        match (painted_at(loaders::DEFAULT_BASE), fills.first()) {
            (Some(p), _) => println!(
                "startup  : {} -- NO LOW BASE",
                painted_reason(loaders::DEFAULT_BASE, p)
            ),
            (None, Some(&(lo, hi, site))) => println!(
                "startup  : fills 0x{lo:08x}..0x{hi:08x} (the loop at 0x{site:08x}){}; clear \
                 of a loader at 0x{:08x}",
                if fills.len() > 1 {
                    format!(" and {} other constant range(s)", fills.len() - 1)
                } else {
                    String::new()
                },
                loaders::DEFAULT_BASE
            ),
            (None, None) => println!("startup  : no fill of a constant range found"),
        }
    }
    // `is_preset`: `base` is the title's own preset, whose window is tried
    // first (`preset_window_base`), as `uexec` does.
    let report_collisions = |base: u32, is_preset: bool| {
        let Some(bytes) = boot_bytes.as_deref() else {
            return;
        };
        let hits = dispatch::literals_in_loader_footprint(bytes, args.address, base);
        let where_ = loaders::live_footprint(base)
            .iter()
            .map(|(lo, hi)| format!("0x{lo:08x}..0x{hi:08x}"))
            .collect::<Vec<_>>()
            .join(" and ");
        if hits.is_empty() {
            println!("overlap  : none -- nothing the title loads points into {where_}");
            return;
        }
        println!(
            "overlap  : {} CONSTANT(S) POINT INTO THE LOADER at {where_}",
            hits.len()
        );
        for (at, site) in hits.iter().take(8) {
            println!("           0x{at:08x} loaded at 0x{site:08x}");
        }
        println!(
            "           If the title writes there the loader is overwritten -- and a \
             Maple DMA does it with no syscall, no packet and no exception."
        );
        // The same policy `uexec` applies, out of the same function, so this
        // cannot drift from what a run would actually do. The answer is what
        // the reader actually needs; without it "pick another base" is an
        // invitation to guess, and a guess costs a session per attempt.
        if is_preset
            && let Some((alt, ceiling)) =
                preset_window_base(&loaders, bytes, args.address, base, seen.as_ref(), sp_min)
        {
            println!(
                "           uexec would use 0x{alt:08x} instead: the top of the preset's \
                 window, under 0x{ceiling:08x}, the lowest address the title names above it \
                 (relocating {} there -- no rebuild).",
                loaders::RELOCATABLE_NAME
            );
            return;
        }
        match pick_clear_base(&loaders, bytes, args.address, base, seen.as_ref(), sp_min) {
            Some(alt) => println!(
                "           uexec would use 0x{alt:08x} instead ({}).",
                if loaders.has(alt) {
                    "a loader built for that address".to_string()
                } else {
                    format!("relocating {} there -- no rebuild", loaders::RELOCATABLE_NAME)
                }
            ),
            None => println!(
                "           Nowhere clear of it, so uexec would go ahead here. Note this \
                 only sees constants: a heap that grows into the loader has none."
            ),
        }
    };
    // A WINDOWS CE TITLE IS PLACED BY ITS OWN ROM HEADER, ahead of any preset
    // (`wanted_loader_base`), so a preset report would describe a decision no
    // run takes.
    if let Some(base) = boot_bytes
        .as_deref()
        .filter(|_| framed_wince)
        .and_then(|b| wince::romhdr(b, args.address))
        .and_then(|h| wince::loader_base(&h, loaders::LOADER_SPAN))
    {
        println!(
            "would use: 0x{base:08x} -- the top of Windows CE's RAM, taken out of it at \
             upload; the preset is not consulted"
        );
        report_collisions(base, false);
        return ExitCode::SUCCESS;
    }
    let (db_path, db_searched) = game_db_path(args, &loaders);
    match presets::PresetDb::load(&db_path) {
        Err(e) => println!(
            "preset   : no database at {} ({e})\n           looked in: {}",
            db_path.display(),
            db_searched
        ),
        Ok(db) => match db.lookup(&identity) {
            None if painted_at(loaders::DEFAULT_BASE).is_some()
                || !low_base_has_stack_headroom(&loaders, loaders::DEFAULT_BASE, sp_min) =>
            {
                // The same branch `uexec` takes for a title the database does
                // not know, from the stock base the CD boots at.
                match boot_bytes.as_deref().and_then(|b| {
                    base_off_the_low_family(
                        &loaders,
                        b,
                        args.address,
                        seen.as_ref(),
                        sp_min,
                        loaders::SCRATCH_BASE,
                    )
                }) {
                    Some(alt) => {
                        println!(
                            "preset   : not in the database ({} rows); would leave 0x{:08x} \
                             for 0x{alt:08x}, off the low family",
                            db.len(),
                            loaders::DEFAULT_BASE
                        );
                        report_collisions(alt, false);
                    }
                    None => {
                        println!(
                            "preset   : not in the database ({} rows); nothing clear of the \
                             low family, so it would stay at 0x{:08x} and be overwritten",
                            db.len(),
                            loaders::DEFAULT_BASE
                        );
                        report_collisions(loaders::DEFAULT_BASE, false);
                    }
                }
            }
            None => {
                println!(
                    "preset   : not in the database ({} rows); would stay at 0x{:08x}",
                    db.len(),
                    loaders::DEFAULT_BASE
                );
                report_collisions(loaders::DEFAULT_BASE, false);
            }
            Some((p, kind)) => {
                let how = match kind {
                    presets::MatchKind::BootSectorMd5 => "exact (boot-sector md5)".to_string(),
                    presets::MatchKind::Title => {
                        let n = db.title_ambiguity(&identity.title);
                        if n > 1 {
                            format!("BY TITLE, ambiguous ({n} different addresses)")
                        } else {
                            "by title".to_string()
                        }
                    }
                };
                println!("preset   : '{}' -- {}", p.title, how);
                println!("memory   : 0x{:08x}", p.memory);
                println!(
                    "loader   : {}",
                    if let Some(reason) = loaders::known_unsupported(p.memory) {
                        format!("UNSUPPORTED base -- {reason}")
                    } else if loaders.has(p.memory) {
                        format!("{} present", loaders.path_for(p.memory).display())
                    } else if loaders.can_provide(p.memory) {
                        format!(
                            "no dcload-0x{:08x}.elf, {} relocated to it",
                            p.memory,
                            loaders::RELOCATABLE_NAME
                        )
                    } else {
                        format!(
                            "MISSING dcload-0x{:08x}.elf in {} (looked in: {})",
                            p.memory,
                            loaders.dir().display(),
                            loaders.searched()
                        )
                    }
                );
                for note in p.unsupported() {
                    println!("not done : {note}");
                }
                // The same two functions `uexec` calls, so this report cannot
                // drift from what a run would do -- including for a preset this
                // host cannot build, where "would stay put" was the old answer
                // and is the one the preset rules out.
                let contested = low_family_contested(&db, &identity, &p);
                let no_headroom = !low_base_has_stack_headroom(&loaders, p.memory, sp_min);
                // Already said on the `startup` line.
                let painted = painted_at(p.memory).is_some();
                let unprovidable = !loaders::is_high(p.memory) && !loaders.can_provide(p.memory);
                if loaders::known_unsupported(p.memory).is_some() {
                    match boot_bytes.as_deref().and_then(|b| {
                        base_for_low_preset(&loaders, b, args.address, seen.as_ref(), sp_min)
                    }) {
                        Some(alt) => {
                            println!(
                                "would use: 0x{alt:08x} -- 0x{:08x} and 0x{:08x} are ruled out \
                                 by a preset this low",
                                loaders::ISOLDR_DEFAULT_ADDR,
                                loaders::ISOLDR_HIGH_ADDR
                            );
                            report_collisions(alt, false);
                        }
                        None => println!(
                            "would use: nothing clear of this title could be produced; the \
                             loader would stay where it is"
                        ),
                    }
                } else if contested.is_some() || no_headroom || painted || unprovidable {
                    // THE SAME PREDICATES `uexec` APPLIES, so the offline
                    // report cannot come to a different answer than a run.
                    if unprovidable {
                        println!(
                            "too big  : the loader set cannot be placed at 0x{:08x} -- its \
                             image no longer fits under the BIOS VBR",
                            p.memory
                        );
                    }
                    if let Some(votes) = contested.as_ref() {
                        println!(
                            "contested: presets under this title disagree ({}) and one is \
                             below 0x{:08x} -- DreamShell only goes there once its default \
                             and its high option have failed",
                            votes
                                .iter()
                                .map(|m| format!("0x{m:08x}"))
                                .collect::<Vec<_>>()
                                .join(" and "),
                            loaders::DEFAULT_BASE,
                        );
                    }
                    if no_headroom {
                        println!(
                            "no room  : this title's measured stack leaves less than {} bytes \
                             under a loader at 0x{:08x}",
                            loaders::LOW_BASE_MIN_MARGIN,
                            p.memory,
                        );
                    }
                    match boot_bytes.as_deref().and_then(|b| {
                        base_off_the_low_family(
                            &loaders,
                            b,
                            args.address,
                            seen.as_ref(),
                            sp_min,
                            loaders::ISOLDR_HIGH_ADDR,
                        )
                    }) {
                        Some(alt) => {
                            println!(
                                "would use: 0x{alt:08x} -- off the low family, seeded from \
                                 0x{:08x}, DreamShell's own answer when low RAM is not \
                                 workable",
                                loaders::ISOLDR_HIGH_ADDR
                            );
                            report_collisions(alt, false);
                        }
                        None => {
                            println!(
                                "would use: nothing clear of the low family could be produced; \
                                 the preset's 0x{:08x} would be used anyway",
                                p.memory
                            );
                            report_collisions(p.memory, false);
                        }
                    }
                } else {
                    report_collisions(p.memory, true);
                }
            }
        },
    }
    ExitCode::SUCCESS
}

/// A filename taken out of a disc image, made safe to use as a host path.
///
/// The bytes at IP.BIN +0x60 are whatever was mastered there: `iso9660::
/// boot_file_name` stops at a NUL or a space and passes everything else
/// through, separators and `..` included. Only the last component survives
/// here, and only its plain-filename characters; anything else becomes `_`,
/// and a name that is left empty or is `.`/`..` falls back to the usual one.
fn safe_output_name(name: &str) -> String {
    let base = name.rsplit(['/', '\\', ':']).next().unwrap_or(name);
    let cleaned: String = base
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-') {
                c
            } else {
                '_'
            }
        })
        .collect();
    // A leading dot is the last thing left that the image gets to decide and
    // the user does not see: `.bashrc` lands in the working directory and does
    // not show up in an `ls`. No boot binary is named that way.
    let cleaned = cleaned.trim_start_matches('.');
    if cleaned.trim_matches('.').is_empty() {
        return "1ST_READ.BIN".to_string();
    }
    cleaned.to_string()
}

/// `extract`: the boot binary out of an image and onto disk.
fn extract_only(args: &Args, disc: &str, output: Option<&str>) -> ExitCode {
    let boot = match dispatch::boot_binary(disc, args.descramble.into(), args.wince_mode()) {
        Ok(b) => b,
        Err(e) => {
            error!("{e}");
            return ExitCode::FAILURE;
        }
    };
    // `-o` is a path the USER typed and is taken as it lies. The default is
    // not: it comes out of IP.BIN's sixteen-byte filename field, byte for
    // byte, and nothing in the image stops that field reading `../../.bashrc`.
    // Writing it verbatim would let the image choose where the host writes.
    let default = safe_output_name(&boot.name);
    let out = output.unwrap_or(&default);
    if let Err(e) = std::fs::write(out, &boot.bytes) {
        error!("cannot write {out}: {e}");
        return ExitCode::FAILURE;
    }
    info!(
        "{} -> {out} ({} bytes, md5 {:x}){}",
        boot.name,
        boot.bytes.len(),
        md5::compute(&boot.bytes),
        if boot.descrambled { ", unscrambled" } else { "" }
    );
    ExitCode::SUCCESS
}

/// (the table to read, every path considered).
///
/// Resolved exactly like the loader set: beside the loaders, then in the
/// project root, and only then next to the executable -- so `cargo clean`
/// cannot take it and debug and release read the same file. The second half of
/// the pair exists because "no game database at X" names one path and leaves
/// the user guessing about the others.
fn game_db_path(args: &Args, loaders: &loaders::LoaderSet) -> (std::path::PathBuf, String) {
    let exe = std::env::current_exe().ok();
    let cwd = std::env::current_dir().ok();
    let candidates = loaders::game_db_candidates(
        args.game_db.clone(),
        std::env::var("DCLOAD_GAME_DB").ok(),
        loaders.dir(),
        exe.as_deref(),
        cwd.as_deref(),
        env!("CARGO_MANIFEST_DIR"),
    );
    let chosen = candidates
        .iter()
        .find(|p| p.is_file())
        .unwrap_or(&candidates[0])
        .clone();
    let searched = candidates
        .iter()
        .map(|p| p.display().to_string())
        .collect::<Vec<_>>()
        .join(", ");
    (chosen, searched)
}

/// Everything the patch library has to say about this image, worked out once.
///
/// Split out from applying it so `identify` can print the same answer with no
/// console attached -- which is where it is worth the most: a patch that does
/// not fit is a fact about two files, and finding it out offline costs one
/// command instead of a session.
fn patch_plan(args: &Args, payload: &[u8], disc_md5: Option<&str>) -> patchdb::Plan {
    let loaders = loaders::LoaderSet::discover(args.loader_dir.clone());
    let db = patchdb::PatchDb::discover(args.patch_dir.clone(), loaders.dir());
    patchdb::plan(&db, disc_md5, payload, &args.ppf, !args.no_ppf)
}

/// Patch the payload in place, and hand back the words a reload has to undo.
///
/// BEFORE THE UPLOAD, on purpose. The alternative -- poking the words in
/// afterwards, as `--patch` does -- costs a round trip each and, worse, puts
/// the bytes outside everything that checks the transfer: the read-back
/// verification would compare the console against an image the host itself no
/// longer agrees with. Patching the buffer means what is uploaded is what runs
/// and what was verified, and the scans that follow (`literals_in_loader_footprint`,
/// the GAPS probe, the cable check) all look at the code that will actually
/// execute.
///
/// The returned words are for `dispatch::receive_syscalls`' reload guard. A
/// title is free to read its own binary back off the disc, and one that does
/// would otherwise undo the patch several seconds into its own start-up --
/// silently, since nothing on either side is watching those bytes.
fn apply_ppf_patches(
    args: &Args,
    payload: &mut [u8],
    identity: Option<&presets::DiscIdentity>,
) -> Vec<(u32, u32)> {
    let plan = patch_plan(args, payload, identity.map(|i| i.md5.as_str()));
    for p in &plan.problems {
        error!("{p}");
    }
    let mut guard = Vec::new();
    for chosen in &plan.apply {
        let applied = match chosen.ppf.apply(payload) {
            Ok(a) => a,
            Err(e) => {
                error!("{}: {e}", chosen.name);
                continue;
            }
        };
        if applied.already_applied() {
            info!(
                "{} is already applied to this image -- nothing to do",
                chosen.describe()
            );
            continue;
        }
        info!("patching the title with {}", chosen.describe());
        if !chosen.note.is_empty() {
            info!("    {}", chosen.note.lines().next().unwrap_or_default().trim());
        }
        for c in applied.changed.iter().take(16) {
            info!(
                "    0x{:06x}: {:02x} -> {:02x}  (0x{:08x} in RAM)",
                c.offset,
                c.from,
                c.to,
                args.address.wrapping_add(c.offset as u32)
            );
        }
        if applied.changed.len() > 16 {
            info!("    ... and {} more bytes", applied.changed.len() - 16);
        }
        guard.extend(patchdb::guard_words(&applied.changed, payload, args.address));
    }
    // Said even when nothing was applied: "there is a patch for this game and
    // it is not on" is exactly what somebody staring at a black screen needs,
    // and it is one line.
    for chosen in &plan.offer {
        info!(
            "a patch is AVAILABLE and was not applied: {} -- pass --ppf to use it",
            chosen.describe()
        );
    }
    guard.sort_unstable();
    guard.dedup();
    guard
}

/// Where the learned memory map is read from and written back to.
fn memory_db_path(args: &Args, loaders: &loaders::LoaderSet) -> std::path::PathBuf {
    let exe = std::env::current_exe().ok();
    let cwd = std::env::current_dir().ok();
    let candidates = loaders::memory_db_candidates(
        args.memory_db.clone(),
        std::env::var("DCLOAD_MEMORY_DB").ok(),
        loaders.dir(),
        exe.as_deref(),
        cwd.as_deref(),
        env!("CARGO_MANIFEST_DIR"),
    );
    if let Some(found) = candidates.iter().find(|p| p.is_file()) {
        return found.clone();
    }
    // Nothing yet, so this run creates it -- BESIDE THE PRESET DATABASE, not in
    // whichever directory happened to be searched first. The two are read
    // together, shipped together and committed together; a memory map that
    // lands somewhere else is one the next deployment does not carry.
    let (presets, _) = game_db_path(args, loaders);
    if let Some(dir) = presets.parent().filter(|d| d.is_dir()) {
        return dir.join("game-memory.tsv");
    }
    candidates[0].clone()
}

fn main() -> Result<ExitCode, Box<dyn std::error::Error>> {
    let args = Args::parse();
    // Logging goes through the progress display (see `ui`), so that a log
    // record never lands on top of a bar that is being drawn.
    ui::init_logging(args.verbose);
    // BEFORE anything can take time. A run spends its first seconds
    // chainloading a loader and pushing megabytes at the console, and a Ctrl-C
    // in that window used to be an outright kill because the handler was not
    // installed until the title was already running. This also starts the
    // ticker that keeps the learned memory map on disk -- read
    // `memmap::install_signal_handler` for why that ticker, and not the
    // handler, is what actually saves the file.
    memmap::install_signal_handler();
    // Before the socket: these never talk to a Dreamcast.
    if let Commands::Identify { ref disc } = args.command {
        return Ok(identify_only(&args, disc));
    }
    if let Commands::Relocate {
        ref elf,
        to,
        ref output,
    } = args.command
    {
        let bytes = match std::fs::read(elf) {
            Ok(b) => b,
            Err(e) => {
                error!("cannot read {elf}: {e}");
                return Ok(ExitCode::FAILURE);
            }
        };
        return Ok(match loaders::relocate(&bytes, to) {
            Ok(moved) => match std::fs::write(output, &moved) {
                Ok(()) => {
                    println!("{elf} -> {output}, based at 0x{to:08x} ({} bytes)", moved.len());
                    ExitCode::SUCCESS
                }
                Err(e) => {
                    error!("cannot write {output}: {e}");
                    ExitCode::FAILURE
                }
            },
            Err(e) => {
                error!("cannot relocate {elf}: {e}");
                ExitCode::FAILURE
            }
        });
    }
    if let Commands::Extract {
        ref disc,
        ref output,
    } = args.command
    {
        return Ok(extract_only(&args, disc, output.as_deref()));
    }
    if let Commands::AuditAudio { ref disc, track } = args.command {
        let reader = match dispatch::open_disc(disc) {
            Ok(d) => d,
            Err(reason) => {
                error!("{reason}");
                return Ok(ExitCode::FAILURE);
            }
        };
        return Ok(match dispatch::audit_audio(reader.as_ref(), track) {
            Ok(0) => {
                info!(
                    "no ALIGNED discontinuity in this image's audio: every track's big \
                     steps are spread evenly inside a sector, which is what loud music \
                     looks like. Big steps on their own prove nothing -- a full-scale \
                     44.1 kHz signal may legally step by 65534 between samples, and this \
                     test was measured blind to a spliced ring, so only the alignment is \
                     evidence."
                );
                ExitCode::SUCCESS
            }
            Ok(n) => {
                warn!(
                    "{n} step(s) in this image's audio land at ONE offset inside a \
                     sector. Music is aligned to nothing, so that is damage in the dump \
                     or a fault in this reader -- the tracks and offsets are listed \
                     above, and the same stretch will crackle however it is played."
                );
                ExitCode::SUCCESS
            }
            Err(e) => {
                error!("{e}");
                ExitCode::FAILURE
            }
        });
    }

    let legacy_mode = protocol_version()[0] < 2;
    let remote_port = if legacy_mode { 31313 } else { args.port };
    let local_port = if legacy_mode { Some(31313) } else { None };
    let mut udpsender = DcIoUDP::new(args.host.clone(), remote_port, local_port)?;
    let contact = if args.infinite {
        // Said here rather than inside the wait, because this is where the
        // address being polled is known -- and in a redirected log, where no
        // spinner is drawn, this line is the only thing between the command
        // and a minute of silence.
        info!(
            "waiting for dcload-ip on host {} port {} to answer (Ctrl-C to give up)",
            args.host, remote_port
        );
        dispatch::wait_for_any_loader(&mut udpsender)
    } else {
        dispatch::query_loader(&mut udpsender)
    };
    let reply = match contact {
        Err(err) => {
            error!("Failed to contact the client: {}", err);
            error!(
                "if the console is not up yet, --infinite waits for it instead \
                 of giving up here"
            );
            return Ok(ExitCode::FAILURE);
        }
        Ok(v) => v,
    };
    let version_text = reply.text;
    let mut running_base = reply.base;
    info!(
        "Successfully connected to dcload-ip on host {} using port {}",
        args.host, args.port
    );
    match reply.cable {
        Some(cable) => info!("video cable: {}", cable.name()),
        // Not a warning: it only matters if --vga auto is asked for something,
        // and the decision itself says so when it is.
        None => debug!("this loader does not report which video cable is plugged in"),
    }
    match running_base {
        Some(base) => info!("dcload-ip version: {} (loaded at 0x{:08x})", version_text, base),
        None => info!(
            "dcload-ip version: {} (does not report its load address; \
             this build cannot be relocated per game)",
            version_text
        ),
    }

    // Which image answers the title's disc reads. Worked out once, here,
    // because it decides both where the loader goes and what the syscall loop
    // is handed -- and those two disagreeing is a session with the right game
    // running at the wrong address.
    let redirect_disc: Option<String> = match &args.command {
        Commands::UExec {
            file, disc, mount, ..
        } => effective_disc(file, disc, mount),
        _ => None,
    };

    // Opened ONCE, here, and handed to everything that needs it: the identity
    // pass, the boot binary, IP.BIN and the syscall loop. Each `open_disc`
    // re-reads a zip's central directory, re-probes every CDI track for a PVD
    // and re-opens every GDI track file -- only the deflate index survives
    // between opens -- so a run that opened per use paid for all of that four
    // times before the title started.
    //
    // A failure here is reported and is not fatal: the title is still uploaded
    // and started, exactly as before, and every disc read it makes then fails.
    let mut disc_reader: Option<Box<dyn disc_formats::types::DiscFormat>> = None;
    if let Some(path) = redirect_disc.as_deref() {
        match dispatch::open_disc(path) {
            Ok(disc) => disc_reader = Some(disc),
            Err(e) => {
                error!("CDFS redirection DISABLED: {e}");
                error!("the title will be started anyway, and every disc read it makes will fail");
            }
        }
    }

    // Relocate BEFORE uploading the title. Any chainload replaces the whole
    // loader, so a title uploaded first would be uploaded into an image that is
    // about to be overwritten -- and the game's own RAM is zero-filled by the
    // loader that comes up.
    //
    // AND "STAY WHERE YOU ARE" STILL GOES THROUGH ensure_loader_base. It used
    // to return early on None, so a session told to use a particular loader set
    // never checked that the loader on the console came from it -- and a
    // rebuilt set at the same address was silently not picked up. Measured
    // 2026-09-04: a run with `--loader-dir loaders-tone` kept the ADPCM loader
    // already at 0x8ce00000 and played the music exactly as before, which is
    // the one outcome that experiment could not tell apart from a result. The
    // evidence was in the log, twice, phrased as an instrument failing rather
    // than as the wrong loader running. `want == running` costs one round trip
    // and no upload when the image already matches.
    if matches!(args.command, Commands::UExec { .. })
        && let Some(want) = wanted_loader_base(
            &args,
            running_base,
            disc_reader.as_deref().zip(redirect_disc.as_deref()),
        )
        .or(running_base)
    {
        match running_base {
            Some(base) => {
                let loaders = loaders::LoaderSet::discover(args.loader_dir.clone());
                running_base = Some(dispatch::ensure_loader_base(
                    &mut udpsender,
                    &loaders,
                    base,
                    want,
                ));
            }
            None => warn!(
                "this title wants the loader at 0x{want:08x}, but the loader on the \
                 console does not report where it is, so it cannot be moved safely. \
                 Rebuild dcload-ip and re-burn its boot image (or re-run the CD/CDI) \
                 to get a loader that does."
            ),
        }
    }

    let result: Result<ExitCode, Box<dyn std::error::Error>> = match args.command {
        Commands::UExec {
            ref file,
            ref mount,
            console,
            ..
        } => {
            // A disc image resolves to the boot binary it names; anything else
            // is uploaded as it lies.
            // The same image, when `uexec <image>` was given without `-d`.
            let payload_disc = disc_reader
                .as_deref()
                .filter(|_| redirect_disc.as_deref() == Some(file.as_str()));
            let (mut payload, label, wince) = match resolve_payload(&args, file, payload_disc) {
                Ok(p) => p,
                Err(e) => {
                    error!("{e}");
                    return Ok(ExitCode::FAILURE);
                }
            };
            // Which dump this is, computed once and used twice: the patch
            // library keys on it, and so does the learned memory map further
            // down. Reading the boot sector twice would cost nothing; having
            // two answers to "what game is this" would.
            let identity = disc_reader
                .as_deref()
                .zip(redirect_disc.as_deref())
                .and_then(|(d, p)| dispatch::identify(d, p).ok());
            // BEFORE the upload, so what goes over the wire is what runs --
            // see `apply_ppf_patches`. These words join the GAPS and cable
            // guards below, because a title can reload its own image.
            let ppf_guard = apply_ppf_patches(&args, &mut payload, identity.as_ref());
            let has_disc = redirect_disc.is_some();
            match dispatch::upload_bytes(
                &mut udpsender,
                &payload,
                &label,
                args.address,
                running_base,
            ) {
            Err(e) => Err(e),
            Ok((addr, _size)) => {
                // After the title, before EXEC: the region is clear of both.
                // `boot_ipbin` decides both how much of IP.BIN goes over and
                // where execution starts; if the load fails there is no
                // bootstrap in RAM, so fall back to entering the binary rather
                // than jumping into whatever was there before.
                // WHETHER TO FORCE VGA, decided here because IP.BIN leaves in
                // the next few lines and carries half of it.
                //
                // `auto` asks the console instead of the user, because only
                // the console can answer: dcload reads the cable off PDTRA and
                // reports it, and forcing a title to VGA is exactly right with
                // a VGA box on the other end and a black screen with a
                // television. An older loader says nothing, and unknown is
                // read as "leave it alone" -- the only safe reading, since the
                // code for VGA is 0 and every loose decode lands on it.
                let vga = match args.vga {
                    VgaArg::Never => false,
                    VgaArg::Always => {
                        info!("--vga always: forcing VGA whatever the console reports");
                        true
                    }
                    VgaArg::Auto => match dispatch::query_cable(&mut udpsender) {
                        Some(loaders::Cable::Vga) => {
                            info!("the console reports a VGA box; patching this title for it");
                            true
                        }
                        Some(other) => {
                            info!(
                                "the console reports {}, so the title is left as shipped \
                                 (--vga always overrides this)",
                                other.name()
                            );
                            false
                        }
                        None => {
                            info!(
                                "this loader does not report which cable is plugged in, so the \
                                 title is left as shipped -- rebuild the loaders for --vga auto \
                                 to decide, or pass --vga always"
                            );
                            false
                        }
                    },
                };
                // A WINDOWS CE TITLE IS ENTERED THROUGH THE DISC'S OWN
                // SECOND BOOTSTRAP, as if --boot-ipbin had been given. That
                // stub hands over the machine state a real boot does -- SR
                // 0x700000f0, the kilobyte below 0x8c010000 zeroed, entry
                // through P2 -- and go.S differs from it on exactly those
                // (dcload-ip: docs/wince-investigation.md). isoldr enters CE titles
                // directly (all 98 of DreamShell's type=3 presets say
                // mode=0), so this is fidelity to the disc, not to isoldr.
                let boot_ipbin = args.boot_ipbin || (wince && !args.no_wince);
                if boot_ipbin && !args.boot_ipbin {
                    info!(
                        "Windows CE title: entering it through the disc's own second \
                         bootstrap, as --boot-ipbin does (--no-wince enters it directly)"
                    );
                }
                let mut entry = addr;
                if let (Some(reader), Some(d)) = (disc_reader.as_deref(), redirect_disc.as_ref()) {
                    match dispatch::load_ip_bin(
                        &mut udpsender,
                        reader,
                        d,
                        running_base,
                        boot_ipbin,
                        vga,
                    ) {
                        Ok(true) if boot_ipbin => {
                            entry = dispatch::IP_BIN_BOOTSTRAP_2_EXEC;
                        }
                        Ok(false) if boot_ipbin => {
                            // Declined, not failed -- the loader is sitting on
                            // the region. Entering 0x8c00e000 now would jump
                            // into the loader's own image.
                            warn!(
                                "--boot-ipbin declined (see above); entering \
                                 0x{addr:08x} directly"
                            );
                        }
                        Ok(_) => {}
                        Err(e) => {
                            warn!("could not load IP.BIN: {e}");
                            if boot_ipbin {
                                warn!(
                                    "--boot-ipbin asked for, but IP.BIN is not in RAM; \
                                     entering 0x{addr:08x} directly instead"
                                );
                            }
                        }
                    }
                } else if boot_ipbin {
                    if has_disc {
                        warn!(
                            "--boot-ipbin asked for, but the disc image could not be \
                             opened (see above); entering 0x{addr:08x} directly"
                        );
                    } else {
                        warn!("--boot-ipbin needs a disc image; entering 0x{addr:08x} directly");
                    }
                }
                // SAID BEFORE THE TITLE STARTS, WHILE THE BASE CAN STILL
                // BE CHANGED -- because once it is running, nothing can say it.
                // A title that writes over the loader ends the session in
                // silence, and when it does it by DMA (Maple above all) not one
                // byte passes through dcload or through this host. The check is
                // one pass over the image for constants naming RAM the loader
                // occupies, kept honest by requiring an instruction to actually
                // load them.
                if let Some(base) = running_base {
                    let hits =
                        dispatch::literals_in_loader_footprint(&payload, args.address, base);
                    if !hits.is_empty() {
                        error!(
                            "THIS TITLE ADDRESSES RAM THE LOADER IS SITTING IN. The loader at \
                             0x{base:08x} occupies {}, and the title loads {} constant(s) \
                             pointing inside it. If it writes there -- and a Maple DMA list is \
                             filled by the hardware itself -- the loader is overwritten with no \
                             syscall, no packet and no exception: black screen, no further disc \
                             reads, nothing logged at either end. Try another base with \
                             --loader-base.",
                            crate::loaders::live_footprint(base)
                                .iter()
                                .map(|(lo, hi)| format!("0x{lo:08x}..0x{hi:08x}"))
                                .collect::<Vec<_>>()
                                .join(" and "),
                            hits.len(),
                        );
                        for (at, site) in hits.iter().take(8) {
                            error!("    0x{at:08x} loaded at 0x{site:08x}");
                        }
                    }
                }
                // Before --patch, so an explicit patch still wins over it.
                //
                // Kept, not dropped: the words this neutralises live in the
                // title's own image, which a title is free to reload from its
                // disc. `receive_syscalls` watches every read for one landing
                // on them and puts them back, so the guard survives a reload
                // instead of being undone by one.
                let mut gaps_guard: Vec<(u32, u32)> = vec![];
                if !args.no_gaps_guard {
                    gaps_guard = dispatch::gaps_probe_patches(&payload, args.address);
                    if !gaps_guard.is_empty()
                        && let Err(e) = dispatch::apply_patches(&mut udpsender, &gaps_guard)
                    {
                        warn!("could not neutralise the GAPS probe: {e}");
                    }
                }
                // Same mechanism, same reason for surviving a reload: what
                // this changes is one halfword of the title's own image, and a
                // title that reloads that code reads its cable again.
                let mut vga_guard: Vec<(u32, u32)> = vec![];
                if vga {
                    vga_guard = dispatch::vga_cable_patches(&payload, args.address);
                    if vga_guard.is_empty() {
                        warn!(
                            "--vga: no cable check found in this image -- NOTHING was \
                             patched, and the title will see the cable that is really \
                             plugged in. `identify` reports this without a console."
                        );
                    } else if let Err(e) = dispatch::apply_patches(&mut udpsender, &vga_guard) {
                        warn!("could not force the cable check to VGA: {e}");
                    }
                }
                // A title that calls the BIOS GD driver by its own address
                // instead of through the syscall vectors bypasses the
                // emulation and reads the physical drive. Windows CE does
                // (dispatch::gd_body_patches). Always on, found by content:
                // no Katana title measured carries the literal. Guarded like
                // the others, because a module CE reloads carries it again.
                let mut gd_guard: Vec<(u32, u32)> = vec![];
                let direct = dispatch::gd_body_patches(&payload, args.address, 0).len();
                if direct > 0 {
                    match running_base.ok_or_else(|| "the loader does not report its base".to_string())
                        .and_then(|b| gd_bios_entry(&args, b))
                    {
                        Ok(entry) => {
                            info!(
                                "this title calls the BIOS GD driver directly from {direct} \
                                 place(s); pointing them at the loader's emulation (0x{entry:08x})"
                            );
                            gd_guard = dispatch::gd_body_patches(&payload, args.address, entry);
                            if let Err(e) = dispatch::apply_patches(&mut udpsender, &gd_guard) {
                                warn!("could not redirect the direct GD driver calls: {e}");
                            }
                        }
                        Err(e) => warn!(
                            "this title calls the BIOS GD driver directly from {direct} \
                             place(s), and they will reach the real drive: no \
                             _gd_bios_entry in the running loader ({e}) -- redeploy loaders/"
                        ),
                    }
                }
                // WINDOWS CE: its RAM stops where the loader starts, and its GD
                // driver reads by PIO (src/wince.rs). Both are words of the ROM
                // image CE reads in place, guarded like the others.
                let mut wince_guard: Vec<(u32, u32)> = vec![];
                if wince && !args.no_wince {
                    match wince::romhdr(&payload, args.address) {
                        Some(h) => match running_base.and_then(|b| wince::ram_end_patch(&h, b)) {
                            Some(p) => {
                                info!(
                                    "Windows CE: its RAM now ends at 0x{:08x} instead of                                      0x{:08x}, so its kernel never hands out the loader's pages",
                                    p.1, h.ram_end
                                );
                                wince_guard.push(p);
                            }
                            None => info!(
                                "Windows CE: the loader is outside CE's RAM (0x{:08x}..0x{:08x});                                  nothing to take out of it",
                                h.ram_start, h.ram_end
                            ),
                        },
                        None => warn!(
                            "Windows CE: no ROM header found, so the loader's RAM could not be                              taken out of CE's -- expect it to be overwritten"
                        ),
                    }
                    let pio = wince::pio_patches(&payload, args.address);
                    if pio.is_empty() {
                        warn!(
                            "Windows CE: the GD driver's DMA/PIO choice was not found, so aligned                              reads stay on DMA streams, which wait for an interrupt this                              transport never raises -- expect loading to stall"
                        );
                    } else {
                        info!(
                            "Windows CE: its GD driver will read aligned requests by PIO (0x{:08x}),                              whose pieces it chains itself",
                            pio[0].0
                        );
                        wince_guard.extend(pio);
                    }
                    if let Err(e) = dispatch::apply_patches(&mut udpsender, &wince_guard) {
                        warn!("could not patch the Windows CE image: {e}");
                    }
                }
                let guards = [gaps_guard, vga_guard, ppf_guard, gd_guard, wince_guard].concat();
                // Last, so a patch always wins over the bytes it replaces --
                // whether they came from the title, from IP.BIN, or from both.
                if !args.patch.is_empty()
                    && let Err(e) = dispatch::apply_patches(&mut udpsender, &args.patch)
                {
                    warn!("could not apply patches: {e}");
                }
                if !args.probe.is_empty()
                    && let Err(e) =
                        dispatch::apply_probes(&mut udpsender, &args.probe, running_base)
                {
                    warn!("could not place probes: {e}");
                }
                let kos = dispatch::is_kos_binary(&payload);
                // A KOS title from a disc image keeps its console on this
                // host only once the loader knows it is KOS: g_gd_kos also
                // masks interrupts across a disc read's wait, so no thread's
                // printf can enter the loader in the middle of one.
                let kos_told = kos && has_disc && tell_loader_kos(&args, &mut udpsender, running_base);
                if kos {
                    lower_kos_mem_top(&mut udpsender, running_base, &payload, args.address);
                }
                // After the IP.BIN header, which lands in the dead image these
                // words belong to once the loader has moved.
                if let Some(base) = running_base
                    && let Err(e) =
                        dispatch::update_dcload_magic(&mut udpsender, base, !has_disc || kos_told)
                {
                    warn!("could not update the dcload magic: {e}");
                }
                // A VM2/VMUPro selects a game's saves when it is told which
                // game is starting, and the title will ask it for a save long
                // before this host gets another idle moment -- so this goes
                // here, before the instruments and before EXEC. With a disc
                // image only: a homebrew ELF has no product number and there
                // is nothing to select. Never fatal (src/vm2.rs).
                if !args.no_vm2
                    && let Some(id) = identity.as_ref()
                {
                    let name = (!id.title.is_empty()).then_some(id.title.as_str());
                    vm2::announce(&mut udpsender, &id.product, name);
                }
                // Set up BEFORE the title starts, while the disc is still in
                // hand: from here on the reader belongs to the syscall loop.
                // A title with no identity records nothing rather than filing
                // its map under a name that could be any dump.
                let memory_recorder = identity
                    .as_ref()
                    .map(|id| {
                        let path = memory_db_path(&args, &loaders::LoaderSet::discover(
                            args.loader_dir.clone(),
                        ));
                        // What is already known, so the end-of-session report
                        // can say what THIS session added rather than how much
                        // there is in total.
                        let baseline = memmap::MemoryDb::load(&path)
                            .get(&id.md5)
                            .map(|r| r.map)
                            .unwrap_or_default();
                        info!("learning this title's memory map into {}", path.display());
                        std::sync::Arc::new(std::sync::Mutex::new(memmap::MemoryRecorder::new(
                            path, &id.md5, &id.title, baseline,
                        )))
                    });
                // From here the ticker installed at the top of main has
                // something to write, and a Ctrl-C has something to report.
                memmap::set_active(memory_recorder.clone());
                // Before `execute`: the identity check is a blocking round trip
                // and the console is idle right now, which it will not be again
                // until the session ends.
                // Before both instruments, and before the title: this is the
                // last moment the console is idle.
                if let Some(base) = running_base
                    && let Some(rtt) = measure_rtt(&mut udpsender, base)
                {
                    info!(
                        "link: round trip {:.2} ms at rest -- what a disc or audio fetch \
                         cannot go below",
                        rtt.as_secs_f64() * 1e3
                    );
                }
                let diag = start_diag(
                    &args,
                    &mut udpsender,
                    running_base,
                    memory_recorder.clone(),
                );
                // ON WHENEVER THE PANEL IS NOT, and built here for the same
                // reason: its one blocking check belongs in the seconds before
                // the title starts. It costs eight bytes every ten seconds and
                // it is the only thing that can see a title's stack coming (see
                // `stackwatch`). Never alongside the panel -- that samples a
                // range containing the same two counters, and two sinks
                // claiming by address would eat each other's replies -- so the
                // two follow `d` in opposite directions, at their own ticks.
                let stack = start_stack_watch(
                    &args,
                    &mut udpsender,
                    running_base,
                    memory_recorder.clone(),
                );
                // LAST BEFORE EXEC, after everything else that writes RAM: the
                // witness words must be what the title finds (src/marks.rs).
                let image_end = ((args.address & 0x1fff_ffff) | 0x8c00_0000)
                    .saturating_add(payload.len() as u32);
                let marks = start_marks(
                    &args,
                    &mut udpsender,
                    running_base,
                    wince && !args.no_wince,
                    image_end,
                    memory_recorder.clone(),
                );
                info!("Upload complete, executing at 0x{:08x}", entry);
                // The title is on the console now; the host's copy is only
                // holding up to 16 MiB for the length of the session.
                drop(payload);
                match dispatch::execute(&mut udpsender, entry, console || has_disc || mount.is_some(), has_disc) {
                    Err(e) => Err(e),
                    Ok(_) => {
                        if args.cdda_tone {
                            warn!(
                                "--cdda-tone: the disc's audio tracks are NOT being served. \
                                 Every CD-DA read is answered with a synthetic triangle, \
                                 344.5 Hz left and 689.1 Hz right. Anything you hear in \
                                 place of the music is this, not the game."
                            );
                        }
                        if has_disc || mount.is_some() || console {
                            dispatch::receive_syscalls(
                                &mut udpsender,
                                disc_reader,
                                mount.clone(),
                                running_base,
                                &guards,
                                if args.no_cdda {
                                    dispatch::CddaSource::Off
                                } else if args.cdda_tone {
                                    dispatch::CddaSource::Tone
                                } else {
                                    dispatch::CddaSource::Disc
                                },
                                memory_recorder,
                                diag,
                                stack,
                                marks,
                                running_base.map(|b| loader_stage(&args, b)).unwrap_or_default(),
                            )?;
                            return Ok(ExitCode::SUCCESS);
                        }
                        Ok(ExitCode::SUCCESS)
                    }
                }
            }
        }},
        Commands::Upload { ref file } => {
            let (payload, label, _) = match resolve_payload(&args, file, None) {
                Ok(p) => p,
                Err(e) => {
                    error!("{e}");
                    return Ok(ExitCode::FAILURE);
                }
            };
            return match dispatch::upload_bytes(
                &mut udpsender,
                &payload,
                &label,
                args.address,
                running_base,
            )
            .map(|_s| ExitCode::SUCCESS)
            {
                Err(e) => Err(e),
                Ok(code) => {
                    info!("Upload complete");
                    Ok(code)
                }
            };
        }
        // Handled before the socket is opened; unreachable here, but spelled
        // out rather than caught by a wildcard so adding a subcommand keeps
        // failing to compile until it is wired up.
        Commands::Identify { .. }
        | Commands::Extract { .. }
        | Commands::AuditAudio { .. }
        | Commands::Relocate { .. } => {
            unreachable!("handled before connecting")
        }
        Commands::SelftestReadback {} => {
            return match dispatch::selftest_readback(&mut udpsender)? {
                true => Ok(ExitCode::SUCCESS),
                false => Ok(ExitCode::FAILURE),
            };
        }
        Commands::Reboot {} => {
            info!("Sending reboot command");
            dispatch::reboot(&mut udpsender)?;
            info!("Reboot command sent");
            return Ok(ExitCode::SUCCESS);
        } // _ => Err(Box::new(NotImplemented {
          //     feature: "Unknown command".to_string(),
          // })),
    };
    if let Err(returned_error) = result {
        error!("{}", returned_error);
        Ok(ExitCode::FAILURE)
    } else {
        Ok(ExitCode::SUCCESS)
    }
}

