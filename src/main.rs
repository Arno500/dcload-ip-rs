const PROTOCOL_VERSION_LEGACY: [u8; 3] = [0, 0, 0];
const PROTOCOL_VERSION_MODERN: [u8; 3] = [2, 0, 3];
// Keep this easy to toggle. 1024 => legacy mode, 1440 => modern mode.
const CHUNK_SIZE: usize = 1440;

pub(crate) fn protocol_version() -> [u8; 3] {
    if CHUNK_SIZE <= 1024 {
        PROTOCOL_VERSION_LEGACY
    } else {
        PROTOCOL_VERSION_MODERN
    }
}

// Simple program to greet a person
#[derive(Parser, Debug)]
#[command(version, about, long_about = None)]
struct Args {
    /// Verbosity level (-v, -vv)
    #[arg(short, long, action = clap::ArgAction::Count)]
    verbose: Option<u8>,

    /// UDP port to connect to
    #[arg(short, long, default_value_t = 53535)]
    port: u16,

    /// Host to connect to
    #[arg(short = 'H', long, default_value = "", value_hint = clap::ValueHint::Hostname)]
    host: String,

    /// Keep asking for the loader's version until the console answers, instead
    /// of giving up after five tries.
    ///
    /// A START-UP option, and only that: it covers the first VERS exchange --
    /// the one that has to succeed before anything can be uploaded -- so a
    /// session can be launched at a console that is still booting, or not yet
    /// switched on. Once a loader has answered it has no further effect:
    /// every command after that keeps its five tries, because a console that
    /// goes silent mid-session is a failure worth reporting rather than
    /// something to wait out. Ctrl-C ends the wait.
    #[arg(short = 'i', long)]
    infinite: bool,

    /// Address to execute code at
    #[arg(short, long, default_value_t = 0x0c010000, default_value = "0x0c010000", value_parser = maybe_hex::<u32>)]
    address: u32,

    /// Directory of per-base dcload ELFs (dcload-0x8cfe8000.elf, ...).
    /// Defaults to $DCLOAD_LOADER_DIR, else `loaders/` in this project's root
    /// -- the same place for a debug build, a release build and `cargo run`,
    /// and outside `target/` so `cargo clean` leaves it alone. A `loaders`
    /// directory next to the executable is still honoured, last.
    /// Build the set with `make -C target-src/dcload loaders`.
    #[arg(long, value_hint = clap::ValueHint::DirPath)]
    loader_dir: Option<String>,

    /// Per-game settings table (game-presets.tsv, generated by dcload-ip's
    /// scripts/make-preset-db.py from DreamShell's isoldr presets).
    /// Defaults to $DCLOAD_GAME_DB, else game-presets.tsv beside the loaders,
    /// else in this project's root -- outside `target/`, and the same file for
    /// a debug build and a release build.
    #[arg(long, value_hint = clap::ValueHint::FilePath)]
    game_db: Option<String>,

    /// Link the loader at this address instead of asking the database.
    /// `--loader-base 0x8c004000` pins the stock base; use it to check whether
    /// a relocation is what changed a title's behaviour.
    #[arg(long, value_parser = maybe_hex::<u32>)]
    loader_base: Option<u32>,

    /// Never chainload: run whatever loader is already on the console.
    #[arg(long)]
    no_relocate: bool,

    /// Poke a 32-bit word into RAM after the title is uploaded and just before
    /// it runs: `--patch 0x8c0c0d6c=0x0009000b` (that word is `rts; nop`, i.e.
    /// "make this routine do nothing"). Repeatable. The address may be given in
    /// either window. Same mechanism as DreamShell's per-game pa1/pv1 fields --
    /// and, when a title hangs before its first disc read, the only instrument
    /// left: nothing else on the console can be read back at that point.
    #[arg(long, value_parser = parse_patch)]
    patch: Vec<(u32, u32)>,

    /// Apply this PPF patch to the boot binary before uploading it.
    /// Repeatable, and it works on a plain binary as well as on a disc image.
    ///
    /// A PPF is how the scene ships a patch nobody can derive from the code --
    /// a 60 Hz or VGA path a PAL release was built without, say, which is a
    /// different piece of work in every title and so is the one thing `--vga`
    /// cannot do for you. The bytes go into the payload before it is uploaded,
    /// so what runs is what was verified on the way over, and the changed words
    /// join the reload guard in case the title reads its own image back off the
    /// disc.
    ///
    /// A patch that carries a blockcheck and does not match this image is
    /// REFUSED: its offsets mean something else here, and applying it would
    /// write correct bytes into the wrong instructions.
    #[arg(long, value_name = "FILE", value_hint = clap::ValueHint::FilePath)]
    ppf: Vec<String>,

    /// Do not apply the shipped patch library (`patches/patches.tsv`).
    ///
    /// The A/B switch: a title that misbehaves patched and behaves unpatched
    /// costs one run to tell apart. `--ppf` still works -- an off-switch for
    /// the mapping list has no business discarding a file named by hand.
    #[arg(long)]
    no_ppf: bool,

    /// Directory of shipped PPF patches and their `patches.tsv` mapping list.
    /// Defaults to $DCLOAD_PATCH_DIR, else `patches/` beside the loaders, else
    /// in this project's root -- the same search as game-presets.tsv, so the
    /// whole set is one deployment.
    #[arg(long, value_hint = clap::ValueHint::DirPath)]
    patch_dir: Option<String>,

    /// Do not neutralise a title's GAPS-bridge probe.
    ///
    /// By default the host looks in the uploaded image for the signature a
    /// Katana title uses to find an expansion device, and blunts it, because a
    /// title that finds the Broadband Adapter switches it OFF -- see
    /// AGENTS.md 4.12. Pass this to leave the title exactly as shipped and let
    /// dcload's own recovery handle it.
    #[arg(long)]
    no_gaps_guard: bool,

    /// Do not tell a VM2/VMUPro which game is starting.
    ///
    /// By default, with a disc image, the host probes the four Maple ports for
    /// a VM2, a VMUPro or one of the adapters that answer like them, and hands
    /// each one the disc's product number so it selects that game's saves
    /// (`src/vm2.rs`). Pass this to leave the card on whatever it had.
    #[arg(long)]
    no_vm2: bool,

    /// Do not paint witness words in free RAM before EXEC.
    ///
    /// By default, with a disc image the database knows, the loader marks the
    /// RAM no disc read has landed in, and the host learns which 64 KB blocks
    /// the title writes with the CPU while it runs (`src/marks.rs`), into
    /// `game-memory.tsv`. Pass this to leave that RAM as it was.
    #[arg(long)]
    no_marks: bool,

    /// Treat a Windows CE title like any other boot binary.
    ///
    /// By default a disc whose IP.BIN boots `0WINCEOS.BIN` is framed as
    /// DreamShell's isoldr frames it -- the file's first 2048-byte sector is
    /// dropped and the rest loaded at 0x8c010000 -- and is entered through the
    /// disc's own second bootstrap, as `--boot-ipbin` does. Pass this to upload
    /// the file whole and enter it directly, as this host did before.
    #[arg(long)]
    no_wince: bool,

    /// Make the title believe a VGA box is plugged in.
    ///
    /// Two things, both found in the image and both applied before it runs:
    /// the cable check in the title's own code is forced to read "VGA"
    /// (`dispatch::vga_cable_patches`), and the IP.BIN header the loader puts
    /// in RAM is made to declare VGA box support. That is the whole of what a
    /// VGA patch is for a Katana title -- what it cannot do is give a title a
    /// 480p path it was never built with.
    ///
    /// `auto` (the default) ASKS THE CONSOLE. dcload reads the cable off
    /// PDTRA and reports it in its VERS reply, so the host patches only when
    /// there really is a VGA box on the other end -- forcing VGA on a
    /// television is a black screen, and nothing on this side of the wire can
    /// see which is plugged in. A loader too old to report it counts as
    /// unknown, and unknown means "leave the title alone".
    ///
    /// `always` is for the case the console cannot report: an adapter that
    /// does not ground the detect pins (some VGA cables, some HDMI boxes), so
    /// the title is told composite while the display wants 480p.
    #[arg(long, value_enum, default_value_t = VgaArg::Auto, value_name = "auto|always|never")]
    vga: VgaArg,

    /// Refuse the title's CD audio reads, so the game runs without music.
    ///
    /// The engine is on the console (target-src/dcload/cdda.h) and starts by
    /// itself when a title asks to play a track, which it only does when the
    /// table of contents says the disc has audio. This is the A/B switch: a
    /// refused read is answered -1, the loader stops that stream, and the
    /// title keeps its data path -- so "does the music path explain this
    /// behaviour" costs one run and changes nothing else.
    #[arg(long)]
    no_cdda: bool,

    /// Serve a synthetic two-tone triangle instead of the disc's audio tracks:
    /// 344.5 Hz in the left ear, 689.1 Hz in the right.
    ///
    /// Replaces only the disc read: the encoder, the network and the loader
    /// still run. A clean tone clears all of those and leaves this host's
    /// reading of the image as the suspect.
    #[arg(long, conflicts_with = "no_cdda")]
    cdda_tone: bool,

    /// Place a "phone home" probe at ADDR that reports through dcload's own
    /// syscall trampoline: `--probe 0x8c110bec=37` makes the console log
    /// `Write(1, .., 37)` the moment that address is executed. ID is 1..127
    /// and only names the probe. Repeatable.
    ///
    /// Prefer this to a `trapa` patch once a title has started: a title takes
    /// over the exception vectors during its own start-up, and from then on
    /// "the probe fired" and "the probe was never reached" are the same dead
    /// console. This path belongs to the loader, needs no vector table, and
    /// says so in the log. The stub destroys 28 bytes at ADDR and parks there.
    #[arg(long, value_parser = parse_probe)]
    probe: Vec<(u32, u8, Option<u32>)>,

    /// Where to read and write the learned memory map (game-memory.tsv).
    #[arg(long, value_hint = clap::ValueHint::FilePath)]
    memory_db: Option<String>,

    /// What to do about a SCRAMBLED boot binary.
    ///
    /// A binary meant to boot from a CD-R is stored with its 32-byte slices
    /// permuted, and the disc's own bootstrap unpermutes it while loading. This
    /// host never runs that bootstrap -- it enters the binary directly, as
    /// isoldr does -- so a scrambled one has to be undone here or what runs is
    /// noise. A `.gdi` dumped from a GD-ROM is never scrambled; a `.cdi`
    /// self-boot conversion usually is.
    ///
    /// `auto` (the default) undoes it only when it can be PROVEN, which is
    /// possible for homebrew and not for retail titles -- see
    /// `disc_formats::scramble`. If a title uploads cleanly and then does
    /// absolutely nothing, `--descramble always` is the next thing to try.
    #[arg(long, value_enum, default_value_t = DescrambleArg::Auto)]
    descramble: DescrambleArg,

    /// Enter the title through its own IP.BIN bootstrap instead of jumping
    /// straight into 1ST_READ.BIN -- what isoldr does for every preset with
    /// `fastboot = 0`, which includes Sonic Adventure 2.
    ///
    /// Loads all sixteen IP.BIN sectors to 0x8c008000, applies isoldr's four
    /// `Load_IPBin()` patches, and executes 0x8c00e000 (its second bootstrap)
    /// rather than the upload address. Without this the host only ever placed
    /// the single header sector and entered the binary directly, so the code a
    /// real disc runs between the two never ran at all -- and SA2 is the one
    /// title measured reading structures out of that region.
    ///
    /// Needs the loader out of the way: at the stock base dcload's own image
    /// covers 0x8c008000, so this is refused there rather than shooting the
    /// loader mid-upload.
    #[arg(long)]
    boot_ipbin: bool,

    /// Watch dcload's own counters in a panel at the bottom of the screen.
    ///
    /// A DEBUG AID, off by default. The loader keeps a set of always-compiled
    /// counters -- the RX ring's polls and misses, which GD syscalls the title
    /// is making, the CD-DA fetches, the upload accounting -- and this reads
    /// them straight off the console with SendBinQ while the game runs,
    /// highlighting whatever moved since the previous sample. Symbols come from
    /// the very loader image this host uploaded, and the image on the console is
    /// compared against it before a single number is decoded: a mismatch is
    /// refused rather than shown, because counter values from the wrong build
    /// are believable and wrong.
    ///
    /// The panel pages with the arrow keys and PgUp/PgDn -- it pages rather
    /// than scrolls so that a counter never moves between columns; `a` shows
    /// the counters still at zero and `+`/`-` change the sampling rate. It
    /// never enters the terminal's scrollback, so selecting the log above it
    /// copies the log alone.
    ///
    /// `w` WRITES A SNAPSHOT, and it is the only sane way to get the numbers
    /// off the machine. The panel is redrawn on every sample and again before
    /// every log record, and a terminal drops a selection whenever the cells
    /// under it change -- so selecting it is a race nobody wins. `w` prints the
    /// whole set as plain text above the live region, where it never moves
    /// again, and appends the same text to `dcload-diag.txt`. Zeros included:
    /// in a paste of the panel, "absent" and "zero" look identical.
    ///
    /// `d` TURNS THE WHOLE THING ON AND OFF, AT ANY MOMENT, and this flag only
    /// decides which state a session starts in -- so it is not needed to get
    /// the panel, only to have it up from the first second. Off means off: no
    /// sample is asked for, which matters because each one is a round trip
    /// dcload answers from inside `bb->loop()`, i.e. from inside the very
    /// window anyone measuring a title's stutter is trying to measure. While
    /// the panel is off the stack watch has the wire instead, as it does in a
    /// session that never asks for either.
    #[arg(long)]
    diag: bool,

    /// How often --diag re-reads the counters, in seconds.
    ///
    /// Every sample is a UDP round trip that dcload answers from inside the same
    /// loop that serves the title's disc reads, so this is deliberately slow.
    /// Adjustable live from the panel with `+` and `-`.
    #[arg(long, default_value_t = 2.0, value_name = "SECONDS")]
    diag_interval: f64,

    #[command(subcommand)]
    command: Commands,
}

